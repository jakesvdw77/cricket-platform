-- docs/specs/150-managers-and-access-grants.md: roles are named bundles of permissions. The permission LIST lives in code
-- (Permission enum); the bundles live here so custom roles (a later spec) need no further schema change.
CREATE TABLE access_role (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    club_id     UUID REFERENCES club(id),
    key         VARCHAR(40)  NOT NULL,
    name        VARCHAR(80)  NOT NULL,
    description VARCHAR(255) NOT NULL,
    built_in    BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- club_id is null for the built-in, global roles; coalesced so a global key is unique too.
CREATE UNIQUE INDEX ux_access_role_key
    ON access_role (COALESCE(club_id, '00000000-0000-0000-0000-000000000000'), key);

CREATE TABLE access_role_permission (
    role_id    UUID        NOT NULL REFERENCES access_role(id) ON DELETE CASCADE,
    permission VARCHAR(40) NOT NULL,
    PRIMARY KEY (role_id, permission)
);

