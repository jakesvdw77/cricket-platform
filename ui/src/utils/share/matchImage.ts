// docs/specs/131-match-sharing.md (Team selection poster, Countdown poster, Fixture card, Fun facts card; TV summary): ONE
// Canvas2D drawing function for the match images (Square 1080, Portrait 1080 x 1350, Story 1080 x 1920, TV 1920 x 1080).
// The preview and the file use this same function. Every name comes from the MatchShareModel (already through shareName);
// nothing here formats a name. Text sits on a solid panel, never directly on the picture. The picture is held in memory only.

const FONT_STACK = '-apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif'
const WHITE = 'rgb(255, 255, 255)'
const IMAGE_WIDTH = 1080
export const MATCH_IMAGE_HEIGHTS: Record<ImageSize, number> = { SQUARE: 1080, PORTRAIT: 1350, STORY: 1920 }
const TV_WIDTH = 1920
const TV_HEIGHT = 1080
const PLATFORM_CREDIT = 'Generated by Cricket Legend'
const SPONSOR_LABEL = 'Proudly sponsored by'

export type PictureFilter = 'NONE' | 'BLACK_AND_WHITE' | 'SEPIA' | 'VIVID'
export const PICTURE_FILTERS: { value: PictureFilter; label: string }[] = [
  { value: 'NONE', label: 'None' },
  { value: 'BLACK_AND_WHITE', label: 'Black And White' },
  { value: 'SEPIA', label: 'Sepia' },
  { value: 'VIVID', label: 'Vivid' },
]
// Canvas filters only (docs/specs/131): never a pixel read-back.
export const PICTURE_FILTER_CSS: Record<PictureFilter, string> = {
  NONE: 'none',
  BLACK_AND_WHITE: 'grayscale(1)',
  SEPIA: 'sepia(1)',
  VIVID: 'saturate(1.6) contrast(1.05)',
}

export interface PictureSettings {
  // 0 to 1: where the crop window sits along each axis (0.5 centred).
  x: number
  y: number
  // 1 (the whole fitted crop) to 3 (zoomed in).
  zoom: number
  // 0.2 to 1.
  opacity: number
  filter: PictureFilter
}
export const DEFAULT_PICTURE_SETTINGS: PictureSettings = { x: 0.5, y: 0.4, zoom: 1, opacity: 1, filter: 'NONE' }

export interface MatchImageOptions {
  format: 'IMAGE' | 'TV'
  size?: ImageSize
  template: ImageTemplate | TvTemplate
  colour: ResultImageColour
  include: { marks: boolean; venueAndDate: boolean; weather: boolean; picture: boolean }
  logos: { clubUrl: string | null; leagueUrl: string | null; teams: boolean; sponsorUrls: string[] }
  images: Map<string, HTMLImageElement | null>
  clubWebsite?: string | null
  footerLine: boolean
  // The chosen picture, null when none.
  picture: HTMLImageElement | null
  pictureSettings: PictureSettings
}

export function matchImageSize(options: Pick<MatchImageOptions, 'format' | 'size'>): { width: number; height: number } {
  return options.format === 'TV' ? { width: TV_WIDTH, height: TV_HEIGHT } : { width: IMAGE_WIDTH, height: MATCH_IMAGE_HEIGHTS[options.size ?? 'PORTRAIT'] }
}

const clamp = (value: number, low: number, high: number): number => Math.min(high, Math.max(low, value))

// The part of the picture (in its own pixels) shown in a destination box: the box is filled (cropped, never stretched), zoom
// shrinks the window and x, y slide it. Pure, so it is unit tested.
export function pictureCrop(natW: number, natH: number, destW: number, destH: number, settings: Pick<PictureSettings, 'x' | 'y' | 'zoom'>): Rect {
  if (!(natW > 0) || !(natH > 0) || !(destW > 0) || !(destH > 0)) return { x: 0, y: 0, width: natW, height: natH }
  const zoom = clamp(settings.zoom, 1, 3)
  const cover = Math.max(destW / natW, destH / natH)
  const width = destW / cover / zoom
  const height = destH / cover / zoom
  return {
    x: (natW - width) * clamp(settings.x, 0, 1),
    y: (natH - height) * clamp(settings.y, 0, 1),
    width,
    height,
  }
}

interface Palette {
  background: [string, string]
  text: string
  muted: string
  accent: string
  panel: string
  panelText: string
  panelMuted: string
  chip: string
  chipText: string
  card: string
  cardText: string
}

type Kind = 'CLUB' | 'NIGHT' | 'LIGHT'
const kindOf = (template: ImageTemplate | TvTemplate): Kind =>
  template === 'NIGHT' || template === 'BROADCAST' ? 'NIGHT' : template === 'DAYLIGHT' || template === 'LIGHT' ? 'LIGHT' : 'CLUB'

export function matchPalette(template: ImageTemplate | TvTemplate, colour: ResultImageColour): Palette {
  const kind = kindOf(template)
  if (kind === 'NIGHT') {
    return {
      background: [BRAND.ink, BRAND.menu], text: BRAND.cream, muted: BRAND.sand, accent: BRAND.gold,
      panel: BRAND.ink, panelText: BRAND.cream, panelMuted: BRAND.sand, chip: BRAND.gold, chipText: BRAND.ink,
      card: BRAND.cream, cardText: BRAND.ink900,
    }
  }
  if (kind === 'LIGHT') {
    return {
      background: [WHITE, BRAND.groundTop], text: BRAND.ink900, muted: BRAND.inkMuted, accent: BRAND.green700,
      panel: WHITE, panelText: BRAND.ink900, panelMuted: BRAND.inkMuted, chip: BRAND.gold, chipText: BRAND.ink,
      card: WHITE, cardText: BRAND.ink900,
    }
  }
  const onClub = readableOn([colour.main, colour.dark], [colour.contrastText, WHITE, BRAND.ink])
  const onDark = readableOn([colour.dark], [colour.contrastText, WHITE, BRAND.ink])
  return {
    background: [colour.main, colour.dark], text: onClub, muted: onClub, accent: BRAND.gold,
    panel: colour.dark, panelText: onDark, panelMuted: onDark, chip: BRAND.gold, chipText: BRAND.ink,
    card: WHITE, cardText: BRAND.ink900,
  }
}

type Ctx = CanvasRenderingContext2D

interface TextStyle {
  size: number
  colour: string
  weight?: 400 | 500 | 700
  align?: 'left' | 'right' | 'center'
  maxWidth?: number
}

// One line, `y` its vertical middle; shrinks then truncates to fit maxWidth. Returns the width drawn.
function drawText(ctx: Ctx, text: string, x: number, y: number, style: TextStyle): number {
  if (!text) return 0
  let size = style.size
  const weight = style.weight ?? 400
  const setFont = () => {
    ctx.font = `${weight} ${Math.round(size)}px ${FONT_STACK}`
  }
  setFont()
  let shown = text
  if (style.maxWidth !== undefined) {
    const floor = style.size * 0.55
    while (ctx.measureText(shown).width > style.maxWidth && size > floor) {
      size = Math.max(floor, size * 0.94)
      setFont()
    }
    while (shown.length > 1 && ctx.measureText(shown).width > style.maxWidth) shown = `${shown.slice(0, -2).trimEnd()}…`
  }
  ctx.fillStyle = style.colour
  ctx.textAlign = style.align ?? 'left'
  ctx.textBaseline = 'middle'
  ctx.fillText(shown, x, y)
  return ctx.measureText(shown).width
}

function roundedRect(ctx: Ctx, rect: Rect, radius: number, fill: string): void {
  const { x, y, width, height } = rect
  const r = Math.min(radius, width / 2, height / 2)
  ctx.fillStyle = fill
  ctx.beginPath()
  ctx.moveTo(x + r, y)
  ctx.arcTo(x + width, y, x + width, y + height, r)
  ctx.arcTo(x + width, y + height, x, y + height, r)
  ctx.arcTo(x, y + height, x, y, r)
  ctx.arcTo(x, y, x + width, y, r)
  ctx.closePath()
  ctx.fill()
}

const imageFor = (images: MatchImageOptions['images'], url: string | null | undefined): HTMLImageElement | null => (url ? (images.get(url) ?? null) : null)

// A team crest: its logo on a white round backing (aspect kept) or an initial tile when it has none.
function drawCrest(ctx: Ctx, centreX: number, centreY: number, radius: number, name: string, image: HTMLImageElement | null, palette: Palette): void {
  ctx.fillStyle = image ? WHITE : palette.accent
  ctx.beginPath()
  ctx.arc(centreX, centreY, radius, 0, Math.PI * 2)
  ctx.fill()
  if (image) {
    const slot = { x: centreX - radius * 0.78, y: centreY - radius * 0.78, width: radius * 1.56, height: radius * 1.56 }
    const fit = fitLogo(slot, image.naturalWidth || image.width, image.naturalHeight || image.height)
    ctx.drawImage(image, fit.x, fit.y, fit.width, fit.height)
  } else {
    drawText(ctx, (name.trim()[0] ?? '?').toUpperCase(), centreX, centreY, { size: radius * 1.1, colour: BRAND.ink, weight: 700, align: 'center' })
  }
}

function drawPicture(ctx: Ctx, rect: Rect, options: MatchImageOptions, palette: Palette): void {
  ctx.save()
  ctx.beginPath()
  ctx.rect(rect.x, rect.y, rect.width, rect.height)
  ctx.clip()
  ctx.fillStyle = palette.panel
  ctx.fillRect(rect.x, rect.y, rect.width, rect.height)
  const image = options.include.picture ? options.picture : null
  if (image) {
    const crop = pictureCrop(image.naturalWidth || image.width, image.naturalHeight || image.height, rect.width, rect.height, options.pictureSettings)
    ctx.globalAlpha = clamp(options.pictureSettings.opacity, 0.2, 1)
    ctx.filter = PICTURE_FILTER_CSS[options.pictureSettings.filter]
    ctx.drawImage(image, crop.x, crop.y, crop.width, crop.height, rect.x, rect.y, rect.width, rect.height)
    ctx.filter = 'none'
    ctx.globalAlpha = 1
  }
  ctx.restore()
}

function drawChip(ctx: Ctx, text: string, x: number, y: number, size: number, palette: Palette, align: 'left' | 'center', maxWidth: number): void {
  ctx.font = `700 ${Math.round(size)}px ${FONT_STACK}`
  const width = Math.min(maxWidth, ctx.measureText(text).width + size * 1.6)
  const height = size * 1.9
  const left = align === 'center' ? x - width / 2 : x
  roundedRect(ctx, { x: left, y: y - height / 2, width, height }, height / 2, palette.chip)
  drawText(ctx, text, left + width / 2, y, { size, colour: palette.chipText, weight: 700, align: 'center', maxWidth: width - size })
}

function drawLineup(ctx: Ctx, lineup: MatchShareLineup, area: Rect, columns: 1 | 2, options: MatchImageOptions, palette: Palette, rowSize: number, heading: boolean): number {
  let y = area.y
  if (heading) {
    drawText(ctx, lineup.teamName, area.x, y + rowSize * 0.7, { size: rowSize * 1.15, colour: palette.panelText, weight: 700, maxWidth: area.width })
    y += rowSize * 1.7
  }
  const players = lineup.players
  const perColumn = Math.ceil(players.length / columns)
  const rowHeight = rowSize * 1.55
  const columnWidth = (area.width - (columns - 1) * rowSize) / columns
  let position = 0
  const positions = players.map((player) => (player.order != null ? (position += 1) : null))
  players.forEach((player, index) => {
    const column = Math.floor(index / perColumn)
    const row = index % perColumn
    const x = area.x + column * (columnWidth + rowSize)
    const cy = y + row * rowHeight + rowHeight / 2
    const number = positions[index]
    drawText(ctx, number != null ? String(number) : '', x, cy, { size: rowSize, colour: palette.accent, weight: 700 })
    const nameLeft = x + rowSize * 1.7
    const marks = options.include.marks ? `${player.captain ? ' (C)' : ''}${player.keeper ? ' (WK)' : ''}` : ''
    drawText(ctx, `${player.name}${marks}`, nameLeft, cy, { size: rowSize, colour: palette.panelText, weight: 500, maxWidth: columnWidth - rowSize * 1.7 })
  })
  y += perColumn * rowHeight
  if (lineup.twelfthMan) {
    drawText(ctx, `12th man: ${lineup.twelfthMan}`, area.x, y + rowHeight / 2, { size: rowSize * 0.9, colour: palette.panelMuted, maxWidth: area.width })
    y += rowHeight
  }
  return y
}

function competitionLine(model: MatchShareModel): string {
  return [model.leagueName, model.seasonLabel].filter(Boolean).join(' · ')
}

function detailsLine(model: MatchShareModel, options: MatchImageOptions): string {
  return options.include.venueAndDate ? [model.whenLabel, model.venue].filter(Boolean).join(' · ') : ''
}

export function drawMatchImage(target: HTMLCanvasElement | CanvasRenderingContext2D, model: MatchShareModel, options: MatchImageOptions): void {
  const { width, height } = matchImageSize(options)
  let ctx: Ctx | null
  if ('getContext' in target) {
    target.width = width
    target.height = height
    ctx = target.getContext('2d')
  } else {
    ctx = target
  }
  if (!ctx) throw new Error('The image could not be drawn in this browser.')
  const palette = matchPalette(options.template, options.colour)
  const tv = options.format === 'TV'
  const unit = Math.min(width, height)
  const k = unit / 1080

  const gradient = ctx.createLinearGradient(0, 0, width * 0.3, height)
  gradient.addColorStop(0, palette.background[0])
  gradient.addColorStop(1, palette.background[1])
  ctx.fillStyle = gradient
  ctx.fillRect(0, 0, width, height)

  const clubImage = imageFor(options.images, options.logos.clubUrl)
  const leagueImage = imageFor(options.images, options.logos.leagueUrl)
  const sponsorImages = options.logos.sponsorUrls
    .slice(0, MAX_SHARE_SPONSORS)
    .map((url) => imageFor(options.images, url))
    .filter((image): image is HTMLImageElement => image !== null)
  const layout = layoutLogos({
    format: tv ? 'TV' : 'IMAGE',
    width,
    height,
    club: clubImage !== null,
    league: leagueImage !== null,
    teamLogos: false,
    sponsors: sponsorImages.length,
    footerLine: options.footerLine,
  })
  const margin = layout.margin

  // Header: club logo, the competition line, league logo.
  const headerTop = margin
  const headerHeight = layout.club?.height ?? layout.league?.height ?? 0
  const drawSlotLogo = (slot: Rect | null, image: HTMLImageElement | null) => {
    if (!slot || !image) return
    roundedRect(ctx, slot, slot.width * 0.12, WHITE)
    const fit = fitLogo({ x: slot.x + slot.width * 0.08, y: slot.y + slot.height * 0.08, width: slot.width * 0.84, height: slot.height * 0.84 }, image.naturalWidth || image.width, image.naturalHeight || image.height)
    ctx.drawImage(image, fit.x, fit.y, fit.width, fit.height)
  }
  drawSlotLogo(layout.club, clubImage)
  drawSlotLogo(layout.league, leagueImage)
  const competition = competitionLine(model)
  const headerMiddle = headerTop + (headerHeight || 40 * k) / 2
  if (competition) {
    drawText(ctx, competition.toUpperCase(), layout.headerText.x + layout.headerText.width / 2, headerMiddle, { size: 26 * k, colour: palette.muted, weight: 700, align: 'center', maxWidth: layout.headerText.width })
  }

  const top = headerTop + (headerHeight > 0 ? headerHeight : 40 * k) + margin * 0.6
  const bottom = layout.content.y + layout.content.height
  const area: Rect = { x: margin, y: top, width: width - margin * 2, height: Math.max(0, bottom - top) }
  const showTeamLogos = options.logos.teams
  const homeImage = showTeamLogos ? imageFor(options.images, model.homeLogoUrl) : null
  const awayImage = showTeamLogos ? imageFor(options.images, model.awayLogoUrl) : null
  const weather = options.include.weather && model.weather ? model.weather.text : null

  const drawVersus = (centreY: number, crest: number, nameSize: number) => {
    const cx = width / 2
    const gap = crest * 0.5
    if (showTeamLogos) {
      drawCrest(ctx, margin + crest, centreY, crest, model.homeName, homeImage, palette)
      drawCrest(ctx, width - margin - crest, centreY, crest, model.awayName, awayImage, palette)
    }
    const nameWidth = (width - margin * 2 - (showTeamLogos ? crest * 4 + gap * 2 : 0)) / 2 - nameSize * 0.8
    drawText(ctx, model.homeName.toUpperCase(), cx - nameSize * 0.8, centreY, { size: nameSize, colour: palette.text, weight: 700, align: 'right', maxWidth: nameWidth })
    drawText(ctx, 'v', cx, centreY, { size: nameSize * 0.8, colour: palette.accent, weight: 700, align: 'center' })
    drawText(ctx, model.awayName.toUpperCase(), cx + nameSize * 0.8, centreY, { size: nameSize, colour: palette.text, weight: 700, align: 'left', maxWidth: nameWidth })
  }

  if (model.content === 'TEAM_SELECTION') {
    drawSelection(ctx, model, options, palette, area, tv, k, weather, drawChip)
  } else if (model.content === 'COUNTDOWN') {
    const mid = area.y + area.height / 2
    drawText(ctx, (model.countdown ?? '').toUpperCase(), width / 2, mid - 150 * k, { size: (tv ? 150 : 130) * k, colour: palette.accent, weight: 700, align: 'center', maxWidth: area.width })
    drawVersus(mid + 10 * k, 56 * k, 46 * k)
    const details = detailsLine(model, options)
    drawText(ctx, details, width / 2, mid + 130 * k, { size: 34 * k, colour: palette.text, weight: 500, align: 'center', maxWidth: area.width })
    if (weather) drawChip(ctx, weather, width / 2, mid + 200 * k, 30 * k, palette, 'center', area.width)
  } else if (model.content === 'FIXTURE') {
    const mid = area.y + area.height / 2
    drawVersus(mid - 60 * k, 70 * k, 52 * k)
    drawText(ctx, detailsLine(model, options), width / 2, mid + 90 * k, { size: 38 * k, colour: palette.text, weight: 500, align: 'center', maxWidth: area.width })
    if (weather) drawChip(ctx, weather, width / 2, mid + 170 * k, 30 * k, palette, 'center', area.width)
  } else if (model.content === 'FUN_FACTS') {
    drawText(ctx, `${model.homeName} v ${model.awayName}`.toUpperCase(), width / 2, area.y + 40 * k, { size: 52 * k, colour: palette.text, weight: 700, align: 'center', maxWidth: area.width })
    drawText(ctx, detailsLine(model, options), width / 2, area.y + 100 * k, { size: 28 * k, colour: palette.muted, align: 'center', maxWidth: area.width })
    const facts = model.facts.slice(0, 5)
    const cardHeight = Math.min(130 * k, (area.height - 170 * k) / Math.max(1, facts.length) - 14 * k)
    facts.forEach((fact, index) => {
      const y = area.y + 150 * k + index * (cardHeight + 14 * k)
      roundedRect(ctx, { x: area.x, y, width: area.width, height: cardHeight }, 12 * k, palette.card)
      roundedRect(ctx, { x: area.x, y, width: 10 * k, height: cardHeight }, 4 * k, BRAND.green700)
      drawText(ctx, fact.text, area.x + 36 * k, y + cardHeight * 0.4, { size: 36 * k, colour: palette.cardText, weight: 700, maxWidth: area.width - 70 * k })
      drawText(ctx, fact.basis, area.x + 36 * k, y + cardHeight * 0.76, { size: 24 * k, colour: BRAND.inkMuted, maxWidth: area.width - 70 * k })
    })
  }

  // Sponsors and footer.
  if (layout.sponsorLabel) {
    drawText(ctx, SPONSOR_LABEL, width / 2, layout.sponsorLabel.y + layout.sponsorLabel.height / 2, { size: 22 * k, colour: palette.muted, align: 'center' })
    sponsorImages.forEach((image, index) => {
      const slot = layout.sponsors[index]
      if (!slot) return
      roundedRect(ctx, slot, slot.width * 0.1, WHITE)
      const fit = fitLogo({ x: slot.x + 6 * k, y: slot.y + 6 * k, width: slot.width - 12 * k, height: slot.height - 12 * k }, image.naturalWidth || image.width, image.naturalHeight || image.height)
      ctx.drawImage(image, fit.x, fit.y, fit.width, fit.height)
    })
  }
  if (layout.footerText) {
    const site = options.clubWebsite?.trim().replace(/^https?:\/\//i, '').replace(/\/$/, '')
    const middle = layout.footerText.y + layout.footerText.height / 2
    if (site) drawText(ctx, site, layout.footerText.x, middle, { size: 22 * k, colour: palette.muted, maxWidth: layout.footerText.width * 0.5 })
    drawText(ctx, PLATFORM_CREDIT, layout.footerText.x + layout.footerText.width, middle, { size: 22 * k, colour: palette.muted, align: 'right' })
  }
}

type ChipFn = typeof drawChip

// The Team selection poster: the picture beside (landscape, square) or above (portrait, story) a solid panel holding the XI.
function drawSelection(ctx: Ctx, model: MatchShareModel, options: MatchImageOptions, palette: Palette, area: Rect, tv: boolean, k: number, weather: string | null, chip: ChipFn): void {
  const lineups = model.lineups
  const both = lineups.length > 1
  const size = options.size ?? 'PORTRAIT'
  const beside = tv || size === 'SQUARE'
  const pictureShare = both ? (beside ? 0.28 : 0.2) : beside ? (tv ? 0.36 : 0.38) : size === 'STORY' ? 0.34 : 0.36
  const pictureRect: Rect = beside
    ? { x: area.x, y: area.y, width: area.width * pictureShare, height: area.height }
    : { x: area.x, y: area.y, width: area.width, height: area.height * pictureShare }
  drawPicture(ctx, pictureRect, options, palette)
  const gap = 18 * k
  const panel: Rect = beside
    ? { x: pictureRect.x + pictureRect.width + gap, y: area.y, width: area.width - pictureRect.width - gap, height: area.height }
    : { x: area.x, y: pictureRect.y + pictureRect.height + gap, width: area.width, height: area.height - pictureRect.height - gap }
  roundedRect(ctx, panel, 14 * k, palette.panel)
  const inner: Rect = { x: panel.x + 28 * k, y: panel.y + 26 * k, width: panel.width - 56 * k, height: panel.height - 52 * k }

  const title = both ? `${model.homeName} v ${model.awayName}` : `${lineups[0]?.teamName ?? model.homeName}`
  drawText(ctx, 'TEAM SELECTION', inner.x, inner.y + 14 * k, { size: 24 * k, colour: palette.panelMuted, weight: 700, maxWidth: inner.width })
  drawText(ctx, title.toUpperCase(), inner.x, inner.y + 62 * k, { size: 52 * k, colour: palette.panelText, weight: 700, maxWidth: inner.width })
  const versus = both ? '' : `v ${lineups[0] && lineups[0].teamName === model.homeName ? model.awayName : model.homeName}`
  const sub = [versus, options.include.venueAndDate ? [model.whenLabel, model.venue].filter(Boolean).join(' · ') : ''].filter(Boolean).join(' · ')
  drawText(ctx, sub, inner.x, inner.y + 108 * k, { size: 27 * k, colour: palette.panelMuted, maxWidth: inner.width })

  const listTop = inner.y + 150 * k
  const weatherReserve = weather ? 60 * k : 0
  const listArea: Rect = { x: inner.x, y: listTop, width: inner.width, height: inner.y + inner.height - listTop - weatherReserve }
  const rowsNeeded = Math.max(...lineups.map((lineup) => lineup.players.length + (lineup.twelfthMan ? 1 : 0)), 1)
  if (both) {
    const half = (listArea.width - 30 * k) / 2
    lineups.forEach((lineup, index) => {
      const rowSize = Math.min(30 * k, listArea.height / ((rowsNeeded + 2) * 1.55))
      drawLineup(ctx, lineup, { x: listArea.x + index * (half + 30 * k), y: listArea.y, width: half, height: listArea.height }, 1, options, palette, rowSize, true)
    })
  } else if (lineups[0]) {
    const columns: 1 | 2 = beside && !tv ? 1 : tv ? 2 : 2
    const perColumn = Math.ceil(rowsNeeded / columns)
    const rowSize = Math.min(34 * k, listArea.height / ((perColumn + 1) * 1.55))
    drawLineup(ctx, lineups[0], listArea, columns, options, palette, rowSize, false)
  }
  if (weather) chip(ctx, weather, inner.x, inner.y + inner.height - 22 * k, 24 * k, palette, 'left', inner.width)
}

export function generateMatchImage(model: MatchShareModel, options: MatchImageOptions): Promise<Blob> {
  const canvas = document.createElement('canvas')
  drawMatchImage(canvas, model, options)
  return new Promise((resolvePromise, reject) => {
    canvas.toBlob((blob) => (blob ? resolvePromise(blob) : reject(new Error('The image could not be created.'))), 'image/png')
  })
}
