// Drawing helpers

type Ctx = CanvasRenderingContext2D
type Images = Map<string, HTMLImageElement | null>

interface TextStyle {
  size: number
  colour: string
  weight?: 400 | 500 | 700
  align?: 'left' | 'right' | 'center'
  // The text shrinks (to 55% of its size) and then truncates with an ellipsis to fit.
  maxWidth?: number
}

// Draws one line with `y` as its vertical middle; returns the width drawn.
function drawText(ctx: Ctx, text: string, x: number, y: number, style: TextStyle): number {
  if (!text) return 0
  let size = style.size
  const weight = style.weight ?? 400
  const setFont = () => {
    ctx.font = `${weight} ${Math.round(size)}px ${FONT_STACK}`
  }
  setFont()
  let shown = text
  if (style.maxWidth !== undefined) {
    const floor = style.size * 0.55
    while (ctx.measureText(shown).width > style.maxWidth && size > floor) {
      size = Math.max(floor, size * 0.94)
      setFont()
    }
    while (shown.length > 1 && ctx.measureText(shown).width > style.maxWidth) {
      shown = `${shown.slice(0, -2).trimEnd()}…`
    }
  }
  ctx.fillStyle = style.colour
  ctx.textAlign = style.align ?? 'left'
  ctx.textBaseline = 'middle'
  ctx.fillText(shown, x, y)
  return ctx.measureText(shown).width
}

function measure(ctx: Ctx, text: string, size: number, weight: 400 | 500 | 700): number {
  ctx.font = `${weight} ${Math.round(size)}px ${FONT_STACK}`
  return ctx.measureText(text).width
}

function roundedRect(ctx: Ctx, rect: Rect, radius: number, fill: string): void {
  const { x, y, width, height } = rect
  const r = Math.min(radius, width / 2, height / 2)
  ctx.fillStyle = fill
  ctx.beginPath()
  ctx.moveTo(x + r, y)
  ctx.arcTo(x + width, y, x + width, y + height, r)
  ctx.arcTo(x + width, y + height, x, y + height, r)
  ctx.arcTo(x, y + height, x, y, r)
  ctx.arcTo(x, y, x + width, y, r)
  ctx.closePath()
  ctx.fill()
}

const imageFor = (images: Images, url: string | null | undefined): HTMLImageElement | null => (url ? (images.get(url) ?? null) : null)

// A logo on a white backing in its square slot, fitted with its aspect ratio kept (never stretched).
function drawLogo(ctx: Ctx, slot: Rect, image: HTMLImageElement, palette: Palette): void {
  roundedRect(ctx, slot, slot.width * 0.14, palette.backing)
  const inset = slot.width * 0.08
  const inner = {
    x: slot.x + inset,
    y: slot.y + inset,
    width: slot.width - inset * 2,
    height: slot.height - inset * 2,
  }
  const fitted = fitLogo(inner, image.naturalWidth || image.width, image.naturalHeight || image.height)
  ctx.drawImage(image, fitted.x, fitted.y, fitted.width, fitted.height)
}

// A team's logo, or its initial on a tile when it has none or the logo did not load.
function drawTeamMark(ctx: Ctx, slot: Rect, team: ShareTeam, images: Images, palette: Palette): void {
  const image = imageFor(images, team.logoUrl)
  if (image) {
    drawLogo(ctx, slot, image, palette)
    return
  }
  roundedRect(ctx, slot, slot.width * 0.14, palette.tile)
  drawText(ctx, team.name.charAt(0).toUpperCase() || '?', slot.x + slot.width / 2, slot.y + slot.height / 2 + 1, {
    size: slot.height * 0.5,
    colour: palette.tileText,
    weight: 700,
    align: 'center',
  })
}

function scoreParts(text: string): { main: string; sub: string } {
  const match = /^([^()&]*\S)\s+\(([^)]*)\)$/.exec(text)
  return match ? { main: match[1], sub: `${match[2]} ov` } : { main: text, sub: '' }
}

const displayAddress = (website: string): string =>
  website
    .trim()
    .replace(/^https?:\/\//i, '')
    .replace(/\/$/, '')

const battingText = (row: ShareBattingRow): string =>
  `${row.name} ${row.runs ?? 0}${row.notOut ? '*' : ''}${row.balls !== null ? ` (${row.balls})` : ''}`
const bowlingText = (row: ShareBowlingRow): string => `${row.name} ${row.wickets ?? 0}/${row.runs ?? 0}`
const byRuns = (a: ShareBattingRow, b: ShareBattingRow): number => (b.runs ?? 0) - (a.runs ?? 0) || (a.balls ?? 9999) - (b.balls ?? 9999)
const byWickets = (a: ShareBowlingRow, b: ShareBowlingRow): number =>
  (b.wickets ?? 0) - (a.wickets ?? 0) || (a.economy ?? 9999) - (b.economy ?? 9999)

interface Resolved {
  options: ResultImageOptions
  palette: Palette
  width: number
  height: number
  // The logos that are on AND loaded.
  clubImage: HTMLImageElement | null
  leagueImage: HTMLImageElement | null
  sponsorImages: HTMLImageElement[]
}

// The header, sponsor strip and footer both formats share, from the one layout helper. Returns what the body may use.
function drawFrame(ctx: Ctx, resolved: Resolved, layout: ReturnType<typeof layoutLogos>): void {
  const { options, palette, width, height } = resolved
  const unit = Math.min(width, height)
  const gradient = ctx.createLinearGradient(0, 0, width, height)
  gradient.addColorStop(0, palette.background[0])
  gradient.addColorStop(1, palette.background[1])
  ctx.fillStyle = gradient
  ctx.fillRect(0, 0, width, height)

  // Sponsors: a label and a strip of logos on white backings, centred along the bottom.
  if (layout.sponsorLabel && layout.sponsors.length > 0) {
    if (palette.strip) {
      const top = layout.sponsorLabel.y - layout.margin * 0.4
      const bottom = layout.sponsors[layout.sponsors.length - 1].y + layout.sponsors[0].height + layout.margin * 0.4
      ctx.fillStyle = palette.strip
      ctx.fillRect(0, top, width, bottom - top)
    }
    drawText(ctx, SPONSOR_LABEL, width / 2, layout.sponsorLabel.y + layout.sponsorLabel.height / 2, {
      size: Math.max(14, layout.sponsorLabel.height * 0.62),
      colour: palette.muted,
      align: 'center',
      maxWidth: layout.sponsorLabel.width,
    })
    resolved.sponsorImages.forEach((image, index) => {
      const slot = layout.sponsors[index]
      if (slot) drawLogo(ctx, slot, image, palette)
    })
  }

  // Footer line: the web address (only when the club has a website) and the platform credit; both or neither.
  if (options.footerLine && layout.footerText) {
    const rect = layout.footerText
    const size = Math.max(13, Math.min(rect.height * 0.62, unit * 0.026))
    const website = options.clubWebsite?.trim() ? displayAddress(options.clubWebsite) : ''
    const creditWidth = measure(ctx, PLATFORM_CREDIT, size, 400)
    drawText(ctx, PLATFORM_CREDIT, rect.x + rect.width, rect.y + rect.height / 2, { size, colour: palette.muted, align: 'right' })
    if (website) {
      drawText(ctx, website, rect.x, rect.y + rect.height / 2, {
        size,
        colour: palette.muted,
        maxWidth: Math.max(0, rect.width - creditWidth - size * 2),
      })
    }
  }
}

function resolve(options: ResultImageOptions): Resolved {
  const { width, height } = resultImageSize(options)
  const template =
    options.format === 'TV'
      ? (TV_TEMPLATES as string[]).includes(options.template)
        ? (options.template as TvTemplate)
        : TV_TEMPLATES[0]
      : (IMAGE_TEMPLATES as string[]).includes(options.template)
        ? (options.template as ImageTemplate)
        : IMAGE_TEMPLATES[0]
  const palette =
    options.format === 'TV' ? tvPalette(template as TvTemplate, options.colour) : imagePalette(template as ImageTemplate, options.colour)
  const sponsorImages = options.logos.sponsorUrls
    .slice(0, MAX_SHARE_SPONSORS)
    .map((url) => imageFor(options.images, url))
    .filter((image): image is HTMLImageElement => image !== null)
  return {
    options,
    palette,
    width,
    height,
    clubImage: imageFor(options.images, options.logos.clubUrl),
    leagueImage: imageFor(options.images, options.logos.leagueUrl),
    sponsorImages,
  }
}

function layoutFor(resolved: Resolved) {
  return layoutLogos({
    format: resolved.options.format,
    width: resolved.width,
    height: resolved.height,
    club: resolved.clubImage !== null,
    league: resolved.leagueImage !== null,
    teamLogos: false,
    sponsors: resolved.sponsorImages.length,
    footerLine: resolved.options.footerLine,
  })
}

