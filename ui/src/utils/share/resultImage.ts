// docs/specs/114-share-result.md (Image and TV summary): ONE Canvas2D drawing function for the result card (Square 1080,
// Portrait 4:5, Story 9:16) and the TV summary (always 1920 x 1080). Self-contained like leagueSchedulePoster.ts, whose
// helper pattern it copies (loadImageElement resolves null on failure, FONT_STACK, gradients, an initial tile for a team
// with no logo). Every player name is read from the model, which has already formatted it through shareName: nothing here
// ever formats a name. The club colour always comes from the options; the fixed template colours are declared once below.

const FONT_STACK = '-apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif'

// Fixed template colours (the club colour is never among them).
const WHITE = '#ffffff'
const BLACK = '#000000'
const INK = '#14231c'
const NIGHT = { from: '#1b1f24', to: '#0b0d10' }
const DAYLIGHT = { from: '#ffffff', to: '#e9f0ec' }
const BROADCAST = { from: '#16301f', to: '#07100b' }
const TV_LIGHT = { background: '#f4f7f5', strip: '#e6eee9' }

const IMAGE_WIDTH = 1080
const IMAGE_HEIGHTS: Record<ImageSize, number> = {
  SQUARE: 1080,
  PORTRAIT: 1350,
  STORY: 1920,
}
const TV_WIDTH = 1920
const TV_HEIGHT = 1080
const PLATFORM_CREDIT = 'Generated by Cricket Legend'
const SPONSOR_LABEL = 'Proudly sponsored by'

export type ResultImageFormat = 'IMAGE' | 'TV'

// The club colour as the caller reads it from useTheme().palette.primary.
export interface ResultImageColour {
  main: string
  dark: string
  contrastText: string
}

export interface ResultImageLogos {
  // A logo is drawn only when its url is given AND its image loaded; otherwise its slot collapses.
  clubUrl: string | null
  leagueUrl: string | null
  // The Team logos switch: each side gets its logo or, when it has none, an initial tile.
  teams: boolean
  // At most MAX_SHARE_SPONSORS, in order.
  sponsorUrls: string[]
}

export interface ResultImageOptions {
  format: ResultImageFormat
  // Image only; the TV summary is always 1920 x 1080.
  size?: ImageSize
  // An ImageTemplate for IMAGE, a TvTemplate for TV; a value of the other kind falls back to the first template.
  template: ImageTemplate | TvTemplate
  colour: ResultImageColour
  // Image: the top performers lines, the player of the match line, the venue and date line.
  topPerformers?: boolean
  venueAndDate?: boolean
  // Image: the player of the match line. TV: the player of the match in the bottom bar.
  playerOfTheMatch?: boolean
  // TV: performers per innings, and the Batters and Bowlers switches.
  performers?: TvPerformers
  batters?: boolean
  bowlers?: boolean
  logos: ResultImageLogos
  // Pre-loaded by the caller (loadShareLogos); a null or missing entry is a logo that did not load.
  images: Map<string, HTMLImageElement | null>
  // The web address line, shown only when the club has a website (never invented).
  clubWebsite?: string | null
  // The Footer line switch: the web address and the platform credit, both or neither.
  footerLine: boolean
}

export function resultImageSize(options: Pick<ResultImageOptions, 'format' | 'size'>): { width: number; height: number } {
  if (options.format === 'TV') return { width: TV_WIDTH, height: TV_HEIGHT }
  return {
    width: IMAGE_WIDTH,
    height: IMAGE_HEIGHTS[options.size ?? 'SQUARE'],
  }
}

