// The result card (Image)

const CARD = {
  rowHeight: 124,
  rowGap: 24,
  chipGap: 36,
  chipHeight: 76,
  perfGap: 36,
  perfPad: 24,
  perfLine: 52,
  metaGap: 30,
  metaHeight: 36,
}

function drawCard(ctx: Ctx, model: ShareResultModel, resolved: Resolved): void {
  const { options, palette, width, height } = resolved
  const layout = layoutFor(resolved)
  drawFrame(ctx, resolved, layout)
  const { margin } = layout
  const innerWidth = width - margin * 2

  // Header: club logo left, league logo right, "Full time" and the league name between.
  if (layout.club && resolved.clubImage) drawLogo(ctx, layout.club, resolved.clubImage, palette)
  if (layout.league && resolved.leagueImage) drawLogo(ctx, layout.league, resolved.leagueImage, palette)
  const head = layout.headerText
  const headSize = head.height * 0.3
  if (model.leagueName) {
    drawText(ctx, 'FULL TIME', head.x, head.y + head.height * 0.3, {
      size: headSize,
      colour: palette.text,
      weight: 700,
      maxWidth: head.width,
    })
    drawText(ctx, model.leagueName.toUpperCase(), head.x, head.y + head.height * 0.7, {
      size: headSize * 0.9,
      colour: palette.muted,
      maxWidth: head.width,
    })
  } else {
    drawText(ctx, 'FULL TIME', head.x, head.y + head.height / 2, {
      size: headSize,
      colour: palette.text,
      weight: 700,
      maxWidth: head.width,
    })
  }

  // What the body shows.
  const story = resolved.height / resolved.width > 1.7
  const batters = model.innings
    .flatMap((innings) => innings.topBatters)
    .sort(byRuns)
    .slice(0, 2)
  const bowlers = model.innings
    .flatMap((innings) => innings.topBowlers)
    .sort(byWickets)
    .slice(0, 2)
  const perfLines: string[] = []
  if (options.topPerformers !== false) {
    if (story) {
      batters.forEach((row) => perfLines.push(`🏏 ${battingText(row)}`))
      bowlers.forEach((row) => perfLines.push(`🎯 ${bowlingText(row)}`))
    } else {
      if (batters.length > 0) perfLines.push(`🏏 ${batters.map(battingText).join(' · ')}`)
      if (bowlers.length > 0) perfLines.push(`🎯 ${bowlers.map(bowlingText).join(' · ')}`)
    }
  }
  if (options.playerOfTheMatch !== false && model.playerOfTheMatch) perfLines.push(`⭐ Player of the match: ${model.playerOfTheMatch.name}`)
  const meta = options.venueAndDate !== false ? [model.dateLabel, model.venue].filter(Boolean).join(' · ') : ''

  const base =
    CARD.rowHeight * 2 +
    CARD.rowGap +
    CARD.chipGap +
    CARD.chipHeight +
    (perfLines.length > 0 ? CARD.perfGap + 2 + CARD.perfPad + CARD.perfLine * perfLines.length : 0) +
    (meta ? CARD.metaGap + CARD.metaHeight : 0)
  const bodyTop = head.y + head.height + Math.min(width, height) * 0.04
  const bodyBottom = layout.content.y + layout.content.height
  const maxScale = story ? 1.35 : resolved.height > resolved.width ? 1.15 : 1
  const k = Math.max(0.5, Math.min(maxScale, (bodyBottom - bodyTop) / base))
  let y = bodyTop + Math.max(0, (bodyBottom - bodyTop - base * k) / 2)

  // Two team rows: logo or initial tile, the name, the score at the right.
  const rowHeight = CARD.rowHeight * k
  // Row text grows no further than 1.05 so a long team name keeps its room on the tall sizes.
  const kt = Math.min(k, 1.05)
  const subColumn = Math.max(
    ...[model.home, model.away].map((team) =>
      scoreParts(team.scoreText).sub ? measure(ctx, scoreParts(team.scoreText).sub, 34 * kt, 500) + 12 * kt : 0,
    ),
  )
  ;[model.home, model.away].forEach((team) => {
    const mid = y + rowHeight / 2
    let nameX = margin
    if (options.logos.teams) {
      const box = rowHeight * 0.86
      drawTeamMark(ctx, { x: margin, y: mid - box / 2, width: box, height: box }, team, options.images, palette)
      nameX = margin + box + 20 * k
    }
    const { main, sub } = scoreParts(team.scoreText)
    const right = width - margin
    // The overs column has the same width on both rows, so the two scores line up.
    const subWidth = subColumn
    const mainSize = 88 * kt
    const mainWidth = Math.min(measure(ctx, main, mainSize, 700), innerWidth * 0.4)
    drawText(ctx, sub, right, mid + mainSize * 0.12, {
      size: 34 * kt,
      colour: palette.muted,
      weight: 500,
      align: 'right',
    })
    drawText(ctx, main, right - subWidth, mid, {
      size: mainSize,
      colour: palette.text,
      weight: 700,
      align: 'right',
      maxWidth: mainWidth,
    })
    const scoreLeft = right - subWidth - mainWidth
    drawText(ctx, team.name.toUpperCase(), nameX, mid, {
      size: 54 * kt,
      colour: palette.text,
      weight: 700,
      maxWidth: Math.max(60, scoreLeft - nameX - 24 * k),
    })
    y += rowHeight + CARD.rowGap * k
  })
  y += (CARD.chipGap - CARD.rowGap) * k

  // The result margin chip.
  const chipHeight = CARD.chipHeight * k
  const chipText = model.resultLine.toUpperCase()
  const chipSize = 40 * k
  const chipWidth = Math.min(innerWidth, measure(ctx, chipText, chipSize, 500) + 48 * k)
  roundedRect(ctx, { x: margin, y, width: chipWidth, height: chipHeight }, 10 * k, palette.chip)
  drawText(ctx, chipText, margin + 24 * k, y + chipHeight / 2, {
    size: chipSize,
    colour: palette.chipText,
    weight: 500,
    maxWidth: chipWidth - 48 * k,
  })
  y += chipHeight

  if (perfLines.length > 0) {
    y += CARD.perfGap * k
    ctx.fillStyle = palette.rule
    ctx.fillRect(margin, y, innerWidth, 2)
    y += 2 + CARD.perfPad * k
    perfLines.forEach((line) => {
      drawText(ctx, line, margin, y + (CARD.perfLine * k) / 2, {
        size: 34 * k,
        colour: palette.text,
        maxWidth: innerWidth,
      })
      y += CARD.perfLine * k
    })
  }
  if (meta) {
    y += CARD.metaGap * k
    drawText(ctx, meta, margin, y + (CARD.metaHeight * k) / 2, {
      size: 28 * k,
      colour: palette.muted,
      maxWidth: innerWidth,
    })
  }
}

