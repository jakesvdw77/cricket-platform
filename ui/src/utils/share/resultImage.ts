// Colour helpers

type Rgb = [number, number, number]

function parseColour(value: string): Rgb | null {
  const text = value.trim()
  const hex = /^#([0-9a-f]{3}|[0-9a-f]{6})$/i.exec(text)
  if (hex) {
    const digits =
      hex[1].length === 3
        ? hex[1]
            .split('')
            .map((char) => char + char)
            .join('')
        : hex[1]
    const number = parseInt(digits, 16)
    return [(number >> 16) & 255, (number >> 8) & 255, number & 255]
  }
  const rgb = /^rgba?\(\s*(\d+(?:\.\d+)?)[,\s]+(\d+(?:\.\d+)?)[,\s]+(\d+(?:\.\d+)?)/i.exec(text)
  return rgb ? [Number(rgb[1]), Number(rgb[2]), Number(rgb[3])] : null
}

function luminance([r, g, b]: Rgb): number {
  const channel = (value: number) => {
    const scaled = value / 255
    return scaled <= 0.03928 ? scaled / 12.92 : ((scaled + 0.055) / 1.055) ** 2.4
  }
  return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)
}

// WCAG contrast ratio of two colours; 1 when either cannot be read.
export function contrastRatio(a: string, b: string): number {
  const first = parseColour(a)
  const second = parseColour(b)
  if (!first || !second) return 1
  const [high, low] = [luminance(first), luminance(second)].sort((x, y) => y - x)
  return (high + 0.05) / (low + 0.05)
}

// The candidate that reads best on every background (the best worst-case contrast), so text stays readable on a light
// club colour as well as a dark one.
export function readableOn(backgrounds: string[], candidates: string[]): string {
  let best = candidates[0]
  let bestScore = -1
  for (const candidate of candidates) {
    const score = Math.min(...backgrounds.map((background) => contrastRatio(candidate, background)))
    if (score > bestScore) {
      best = candidate
      bestScore = score
    }
  }
  return best
}

function withAlpha(colour: string, alpha: number): string {
  const rgb = parseColour(colour)
  return rgb ? `rgba(${rgb[0]}, ${rgb[1]}, ${rgb[2]}, ${alpha})` : colour
}

const isLight = (colour: string): boolean => {
  const rgb = parseColour(colour)
  return rgb ? luminance(rgb) > 0.4 : false
}

