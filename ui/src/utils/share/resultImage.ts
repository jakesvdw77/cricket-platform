// Draws the card onto a canvas (sizing it) or onto an existing 2D context. The preview and the file use this same function.
export function drawResultImage(
  target: HTMLCanvasElement | CanvasRenderingContext2D,
  model: ShareResultModel,
  options: ResultImageOptions,
): void {
  const resolved = resolve(options)
  let ctx: Ctx | null
  if ('getContext' in target) {
    target.width = resolved.width
    target.height = resolved.height
    ctx = target.getContext('2d')
  } else {
    ctx = target
  }
  if (!ctx) throw new Error('The image could not be drawn in this browser.')
  if (options.format === 'TV') drawTv(ctx, model, resolved)
  else drawCard(ctx, model, resolved)
}

export function generateResultImage(model: ShareResultModel, options: ResultImageOptions): Promise<Blob> {
  const canvas = document.createElement('canvas')
  drawResultImage(canvas, model, options)
  return new Promise((resolvePromise, reject) => {
    canvas.toBlob((blob) => (blob ? resolvePromise(blob) : reject(new Error('The image could not be created.'))), 'image/png')
  })
}

// fetch to blob to object URL to Image, resolving null on any failure so a missing or broken logo never blocks.
async function loadImageElement(url: string): Promise<HTMLImageElement | null> {
  try {
    const response = await fetch(url)
    if (!response.ok) return null
    const blob = await response.blob()
    const objectUrl = URL.createObjectURL(blob)
    const image = await new Promise<HTMLImageElement | null>((resolveImage) => {
      const element = new Image()
      element.onload = () => resolveImage(element)
      element.onerror = () => resolveImage(null)
      element.src = objectUrl
    })
    URL.revokeObjectURL(objectUrl)
    return image
  } catch {
    return null
  }
}

export async function loadShareLogos(urls: string[]): Promise<Map<string, HTMLImageElement | null>> {
  const unique = [...new Set(urls.filter((url) => url !== ''))]
  const loaded = await Promise.all(unique.map((url) => loadImageElement(url)))
  return new Map(unique.map((url, index) => [url, loaded[index]]))
}
