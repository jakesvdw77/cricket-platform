// Palettes

interface Palette {
  background: [string, string]
  text: string
  muted: string
  rule: string
  // The result chip (Image) and the bottom result bar (TV).
  chip: string
  chipText: string
  tile: string
  tileText: string
  backing: string
  headerBar: string | null
  headerText: string
  strip: string | null
}

function imagePalette(template: ImageTemplate, colour: ResultImageColour): Palette {
  const onClub = readableOn([colour.main, colour.dark], [colour.contrastText, WHITE, INK])
  const onMain = readableOn([colour.main], [colour.contrastText, WHITE, INK])
  const base = {
    backing: WHITE,
    headerBar: null,
    headerText: WHITE,
    strip: null,
  }
  if (template === 'NIGHT') {
    return {
      ...base,
      background: [NIGHT.from, NIGHT.to],
      text: WHITE,
      muted: withAlpha(WHITE, 0.75),
      rule: withAlpha(WHITE, 0.25),
      chip: withAlpha(WHITE, 0.14),
      chipText: WHITE,
      tile: withAlpha(WHITE, 0.16),
      tileText: WHITE,
    }
  }
  if (template === 'DAYLIGHT') {
    return {
      ...base,
      background: [DAYLIGHT.from, DAYLIGHT.to],
      text: INK,
      muted: withAlpha(INK, 0.72),
      rule: withAlpha(INK, 0.2),
      chip: colour.main,
      chipText: onMain,
      tile: colour.main,
      tileText: onMain,
    }
  }
  return {
    ...base,
    background: [colour.main, colour.dark],
    text: onClub,
    muted: withAlpha(onClub, 0.8),
    rule: withAlpha(onClub, 0.3),
    chip: withAlpha(onClub, 0.16),
    chipText: onClub,
    tile: withAlpha(onClub, 0.18),
    tileText: onClub,
  }
}

function tvPalette(template: TvTemplate, colour: ResultImageColour): Palette {
  const onMain = readableOn([colour.main], [colour.contrastText, WHITE, INK])
  if (template === 'CLUB') {
    const text = readableOn([colour.main, colour.dark], [colour.contrastText, WHITE, INK])
    const overlay = isLight(text) ? BLACK : WHITE
    return {
      background: [colour.main, colour.dark],
      text,
      muted: withAlpha(text, 0.8),
      rule: withAlpha(text, 0.3),
      chip: WHITE,
      chipText: contrastRatio(colour.dark, WHITE) >= 4.5 ? colour.dark : INK,
      tile: withAlpha(text, 0.18),
      tileText: text,
      backing: WHITE,
      headerBar: withAlpha(overlay, 0.3),
      headerText: text,
      strip: withAlpha(overlay, 0.22),
    }
  }
  if (template === 'LIGHT') {
    return {
      background: [TV_LIGHT.background, TV_LIGHT.background],
      text: INK,
      muted: withAlpha(INK, 0.72),
      rule: withAlpha(INK, 0.2),
      chip: colour.main,
      chipText: onMain,
      tile: colour.main,
      tileText: onMain,
      backing: WHITE,
      headerBar: colour.main,
      headerText: onMain,
      strip: TV_LIGHT.strip,
    }
  }
  return {
    background: [BROADCAST.from, BROADCAST.to],
    text: WHITE,
    muted: withAlpha(WHITE, 0.75),
    rule: withAlpha(WHITE, 0.18),
    chip: colour.main,
    chipText: onMain,
    tile: withAlpha(WHITE, 0.18),
    tileText: WHITE,
    backing: WHITE,
    headerBar: withAlpha(BLACK, 0.35),
    headerText: WHITE,
    strip: withAlpha(BLACK, 0.25),
  }
}

