// The TV summary

const TV = {
  nameRow: 72,
  scoreGap: 10,
  score: 120,
  listGap: 14,
  listLabel: 28,
  listRow: 40,
  winBar: 112,
}

function drawTvPanel(ctx: Ctx, model: ShareResultModel, resolved: Resolved, team: ShareTeam, panel: Rect, k: number): void {
  const { options, palette } = resolved
  const count = options.performers ?? 3
  const batters = model.innings
    .filter((innings) => innings.battingSide === team.side)
    .flatMap((innings) => innings.topBatters)
    .sort(byRuns)
    .slice(0, count)
  const bowlers = model.innings
    .filter((innings) => innings.battingSide !== team.side)
    .flatMap((innings) => innings.topBowlers)
    .sort(byWickets)
    .slice(0, count)

  let y = panel.y
  const nameRow = TV.nameRow * k
  let nameX = panel.x
  if (options.logos.teams) {
    const box = nameRow * 0.92
    drawTeamMark(ctx, { x: panel.x, y: y + (nameRow - box) / 2, width: box, height: box }, team, options.images, palette)
    nameX += box + 18 * k
  }
  drawText(ctx, team.name.toUpperCase(), nameX, y + nameRow / 2, {
    size: 52 * k,
    colour: palette.text,
    weight: 700,
    maxWidth: panel.x + panel.width - nameX,
  })
  y += nameRow + TV.scoreGap * k

  const { main, sub } = scoreParts(team.scoreText)
  const scoreSize = TV.score * k
  const scoreMid = y + scoreSize / 2
  const mainWidth = Math.min(measure(ctx, main, scoreSize, 700), panel.width * 0.78)
  drawText(ctx, main, panel.x, scoreMid, {
    size: scoreSize,
    colour: palette.text,
    weight: 700,
    maxWidth: mainWidth,
  })
  drawText(ctx, sub, panel.x + mainWidth + 16 * k, scoreMid + scoreSize * 0.2, {
    size: 40 * k,
    colour: palette.muted,
    weight: 500,
    maxWidth: panel.width - mainWidth - 16 * k,
  })
  y += scoreSize

  const list = (label: string, rows: { name: string; value: string }[]) => {
    if (rows.length === 0) return
    y += TV.listGap * k
    const labelHeight = TV.listLabel * k
    drawText(ctx, label, panel.x, y + labelHeight / 2, {
      size: 22 * k,
      colour: palette.muted,
      weight: 700,
    })
    y += labelHeight
    rows.forEach((row) => {
      const rowHeight = TV.listRow * k
      const valueWidth = measure(ctx, row.value, 30 * k, 700)
      drawText(ctx, row.value, panel.x + panel.width, y + rowHeight / 2, {
        size: 30 * k,
        colour: palette.text,
        weight: 700,
        align: 'right',
      })
      drawText(ctx, row.name, panel.x, y + rowHeight / 2, {
        size: 30 * k,
        colour: palette.text,
        maxWidth: Math.max(40, panel.width - valueWidth - 20 * k),
      })
      ctx.fillStyle = palette.rule
      ctx.fillRect(panel.x, y + rowHeight - 1, panel.width, 1)
      y += rowHeight
    })
  }
  if (options.batters !== false) {
    list(
      'BATTING',
      batters.map((row) => ({
        name: row.name,
        value: `${row.runs ?? 0}${row.notOut ? '*' : ''}${row.balls !== null ? ` (${row.balls})` : ''}`,
      })),
    )
  }
  if (options.bowlers !== false) {
    list(
      'BOWLING',
      bowlers.map((row) => ({
        name: row.name,
        value: `${row.wickets ?? 0}/${row.runs ?? 0}`,
      })),
    )
  }
}

function drawTv(ctx: Ctx, model: ShareResultModel, resolved: Resolved): void {
  const { options, palette, width } = resolved
  const layout = layoutFor(resolved)
  drawFrame(ctx, resolved, layout)
  const { margin } = layout
  const head = layout.headerText
  const barHeight = head.y + head.height + margin * 0.5
  if (palette.headerBar) {
    ctx.fillStyle = palette.headerBar
    ctx.fillRect(0, 0, width, barHeight)
  }
  if (layout.club && resolved.clubImage) drawLogo(ctx, layout.club, resolved.clubImage, palette)
  if (layout.league && resolved.leagueImage) drawLogo(ctx, layout.league, resolved.leagueImage, palette)
  const title = [model.leagueName?.toUpperCase(), 'MATCH SUMMARY'].filter(Boolean).join(' · ')
  const line = [model.dateLabel, model.venue].filter(Boolean).join(' · ')
  drawText(ctx, title, head.x, head.y + head.height * 0.32, {
    size: head.height * 0.34,
    colour: palette.headerText,
    weight: 700,
    maxWidth: head.width,
  })
  drawText(ctx, line, head.x, head.y + head.height * 0.72, {
    size: head.height * 0.26,
    colour: palette.headerText,
    maxWidth: head.width,
  })

  // Bottom result bar with the player of the match.
  const contentBottom = layout.content.y + layout.content.height
  const barTop = contentBottom - TV.winBar
  ctx.fillStyle = palette.chip
  ctx.fillRect(0, barTop, width, TV.winBar)
  const potm = options.playerOfTheMatch !== false && model.playerOfTheMatch ? `⭐ Player of the match: ${model.playerOfTheMatch.name}` : ''
  const potmWidth = potm ? Math.min(measure(ctx, potm, 34, 500), (width - margin * 2) * 0.45) : 0
  drawText(ctx, potm, width - margin, barTop + TV.winBar / 2, {
    size: 34,
    colour: palette.chipText,
    weight: 500,
    align: 'right',
    maxWidth: potmWidth,
  })
  drawText(ctx, model.resultLine.toUpperCase(), margin, barTop + TV.winBar / 2, {
    size: 52,
    colour: palette.chipText,
    weight: 700,
    maxWidth: width - margin * 2 - potmWidth - (potm ? 40 : 0),
  })

  // Two side panels between the header bar and the result bar.
  const top = barHeight + margin * 0.6
  const bottom = barTop - margin * 0.6
  const lines = (side: ShareTeam['side']): number => {
    const own = model.innings.filter((innings) => innings.battingSide === side)
    const fielding = model.innings.filter((innings) => innings.battingSide !== side)
    const count = options.performers ?? 3
    const batters = options.batters !== false ? Math.min(count, own.flatMap((innings) => innings.topBatters).length) : 0
    const bowlers = options.bowlers !== false ? Math.min(count, fielding.flatMap((innings) => innings.topBowlers).length) : 0
    return (
      (batters > 0 ? TV.listGap + TV.listLabel + batters * TV.listRow : 0) +
      (bowlers > 0 ? TV.listGap + TV.listLabel + bowlers * TV.listRow : 0)
    )
  }
  const base = TV.nameRow + TV.scoreGap + TV.score + Math.max(lines('HOME'), lines('AWAY'))
  const k = Math.max(0.5, Math.min(1.25, (bottom - top) / base))
  const panelTop = top + Math.max(0, (bottom - top - base * k) / 2)
  const half = (width - margin * 2) / 2
  const gutter = margin * 0.5
  ctx.fillStyle = palette.rule
  ctx.fillRect(width / 2, top, 1, Math.max(0, bottom - top))
  drawTvPanel(ctx, model, resolved, model.home, { x: margin, y: panelTop, width: half - gutter, height: bottom - panelTop }, k)
  drawTvPanel(
    ctx,
    model,
    resolved,
    model.away,
    {
      x: margin + half + gutter,
      y: panelTop,
      width: half - gutter,
      height: bottom - panelTop,
    },
    k,
  )
}

