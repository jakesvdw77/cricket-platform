import { jsPDF } from 'jspdf'
import { fitLogo, layoutLogos, MAX_SHARE_SPONSORS } from './logoLayout'
import type { Rect } from './logoLayout'
import { readableOn } from './resultImage'
import type { ResultImageColour } from './resultImage'
import type { PdfTemplate } from './shareChoices'
import type { ShareBattingRow, ShareBowlingRow, ShareInnings, ShareResultModel, ShareTeam } from './shareResultData'

// docs/specs/114-share-result.md (PDF scorecard): an A4 portrait scorecard, mirroring teamSheetPdf.ts (jsPDF, a private
// base64 image loader that resolves null on failure, fixed colours as RGB tuples declared once below, the club colour
// passed IN as a hex from the theme). Every player name is read from the model, which has already formatted it through
// shareName: nothing here ever formats a name. Document metadata and the file name carry team names only. The text is real
// text in the PDF.
//
// The page is first LAID OUT into a list of drawing operations per page (measured with jsPDF itself), and the list is then
// replayed into jsPDF. The screen's preview replays the very same list into a canvas (resultPdfPreview.ts), so what is
// shown is exactly what is made, and the page count is known before "Page n of m" is written.

type Rgb = [number, number, number]

// Fixed template colours (the club colour is never among them).
const WHITE: Rgb = [255, 255, 255]
const INK: Rgb = [20, 35, 28] // theme.palette.text.primary (#14231c)
const MUTED: Rgb = [82, 101, 92] // theme.palette.text.secondary (#52655c)
const RULE: Rgb = [229, 235, 231]
const RULE_STRONG: Rgb = [154, 169, 161]
const BACKING: Rgb = [255, 255, 255]

export const PDF_PAGE_WIDTH = 210
export const PDF_PAGE_HEIGHT = 297
const PLATFORM_CREDIT = 'Generated by Cricket Legend'
const SPONSOR_LABEL = 'Proudly sponsored by'
const MM_PER_PT = 25.4 / 72

export interface ResultPdfLogos {
  clubUrl: string | null
  leagueUrl: string | null
  // The Team logos switch: a side with no logo gets the initial tile.
  teams: boolean
  sponsorUrls: string[]
}

export interface ResultPdfOptions {
  template: PdfTemplate
  // The club colour as the caller reads it from useTheme().palette.primary.
  colour: ResultImageColour
  include: { batting: boolean; bowling: boolean; extras: boolean; toss: boolean; playerOfTheMatch: boolean }
  logos: ResultPdfLogos
  // The club's web address; the footer shows it only when this is given AND the Footer line is on.
  clubWebsite: string | null
  footerLine: boolean
}

type Align = 'left' | 'right' | 'center'
type Font = 'normal' | 'bold' | 'italic'

export type PdfOp =
  | { kind: 'rect'; x: number; y: number; width: number; height: number; radius: number; fill: Rgb }
  | { kind: 'line'; x1: number; y1: number; x2: number; y2: number; colour: Rgb; lineWidth: number }
  | { kind: 'text'; text: string; x: number; y: number; align: Align; font: Font; size: number; colour: Rgb }
  | { kind: 'image'; data: string; x: number; y: number; width: number; height: number }

export interface ResultPdfOutput {
  blob: Blob
  // An object URL for the blob: the caller owns revoking it.
  url: string
  pageCount: number
  // The laid-out pages, for the on-screen preview (an image that jsPDF could not embed is not in them).
  pages: PdfOp[][]
}

// A type scale per template, in points; row heights in millimetres.
interface TypeScale {
  title: number
  subtitle: number
  result: number
  heading: number
  body: number
  small: number
  row: number
  gap: number
}
const SCALE: Record<PdfTemplate, TypeScale> = {
  CLUB: { title: 15, subtitle: 8.5, result: 13, heading: 10, body: 8.5, small: 7, row: 5.4, gap: 5 },
  CLASSIC: { title: 15, subtitle: 8.5, result: 13, heading: 10, body: 8.5, small: 7, row: 5.4, gap: 5 },
  COMPACT: { title: 12, subtitle: 7.5, result: 11, heading: 9, body: 7.5, small: 6.5, row: 4.4, gap: 3.5 },
}

function hexToRgb(hex: string, fallback: Rgb): Rgb {
  const match = /^#?([0-9a-f]{3}|[0-9a-f]{6})$/i.exec(hex.trim())
  if (!match) return fallback
  const digits = match[1].length === 3 ? match[1].replace(/./g, '$&$&') : match[1]
  return [parseInt(digits.slice(0, 2), 16), parseInt(digits.slice(2, 4), 16), parseInt(digits.slice(4, 6), 16)]
}

// fetch → blob → FileReader.readAsDataURL, as teamSheetPdf.ts does; kept private. Resolves null on any failure (network
// error, non-OK response, a FileReader error) so a missing or broken logo never throws or blocks the PDF.
async function loadImageBase64(url: string): Promise<string | null> {
  try {
    const response = await fetch(url)
    if (!response.ok) return null
    const blob = await response.blob()
    return await new Promise<string>((resolve, reject) => {
      const reader = new FileReader()
      reader.onload = () => resolve(reader.result as string)
      reader.onerror = () => reject(reader.error)
      reader.readAsDataURL(blob)
    })
  } catch {
    return null
  }
}

const imageFormat = (data: string): string => (/^data:image\/jpe?g/i.test(data) ? 'JPEG' : 'PNG')

const display = (value: number | null): string => (value === null || value === undefined ? '-' : String(value))
const websiteText = (website: string): string => website.trim().replace(/^https?:\/\//i, '').replace(/\/$/, '')

interface Column {
  title: string
  // Fixed width in mm; the one column without it takes the rest.
  width?: number
  align: Align
  bold?: boolean
}

export async function generateResultPdf(model: ShareResultModel, options: ResultPdfOptions): Promise<ResultPdfOutput> {
  const type = SCALE[options.template]
  const compact = options.template === 'COMPACT'
  const club = hexToRgb(options.colour.main, INK)
  const onClub = hexToRgb(readableOn([options.colour.main], [options.colour.contrastText, '#ffffff', '#14231c']), WHITE)

  // Every logo is fetched once; a logo that fails collapses its slot.
  const sponsorUrls = options.logos.sponsorUrls.slice(0, MAX_SHARE_SPONSORS)
  const teamUrls = options.logos.teams ? [model.home.logoUrl, model.away.logoUrl] : []
  const wanted = [options.logos.clubUrl, options.logos.leagueUrl, ...sponsorUrls, ...teamUrls].filter((url): url is string => Boolean(url))
  const loaded = new Map<string, string | null>(
    await Promise.all([...new Set(wanted)].map(async (url) => [url, await loadImageBase64(url)] as const)),
  )
  const imageOf = (url: string | null): string | null => (url ? (loaded.get(url) ?? null) : null)
  const clubImage = imageOf(options.logos.clubUrl)
  const leagueImage = imageOf(options.logos.leagueUrl)
  const sponsorImages = sponsorUrls.map(imageOf).filter((data): data is string => data !== null)

  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' })
  doc.setProperties({
    // Team names only, whatever the Initials only setting: never a player name.
    title: `${model.home.name} v ${model.away.name}`,
    subject: [model.leagueName, model.dateLabel].filter(Boolean).join(', ') || 'Match scorecard',
    author: model.clubName || 'Cricket Legend',
    creator: 'Cricket Legend',
  })

  const pageW = PDF_PAGE_WIDTH
  const pageH = PDF_PAGE_HEIGHT
  const layout = layoutLogos({
    format: 'PDF',
    width: pageW,
    height: pageH,
    club: clubImage !== null,
    league: leagueImage !== null,
    teamLogos: options.logos.teams,
    sponsors: sponsorImages.length,
    // The page number always needs its line.
    footerLine: true,
  })
  const margin = layout.margin
  const left = margin
  const right = pageW - margin
  const contentW = right - left
  const footerRect = layout.footerText as Rect
  const bottomLimit = (layout.sponsorLabel ? layout.sponsorLabel.y : footerRect.y) - 3

  const pages: PdfOp[][] = [[]]
  let y = 0
  const push = (op: PdfOp) => {
    pages[pages.length - 1].push(op)
  }
  const fillRect = (x: number, top: number, width: number, height: number, colour: Rgb, radius = 0) =>
    push({ kind: 'rect', x, y: top, width, height, radius, fill: colour })
  const line = (x1: number, y1: number, x2: number, colour: Rgb, lineWidth = 0.2) =>
    push({ kind: 'line', x1, y1, x2, y2: y1, colour, lineWidth })
  const text = (value: string, x: number, baseline: number, size: number, colour: Rgb, font: Font = 'normal', align: Align = 'left') => {
    if (value) push({ kind: 'text', text: value, x, y: baseline, align, font, size, colour })
  }
  const measure = (value: string, size: number, font: Font = 'normal'): number => {
    doc.setFont('helvetica', font)
    doc.setFontSize(size)
    return doc.getTextWidth(value)
  }
  // The text shortened with an ellipsis so it fits the width.
  const fit = (value: string, width: number, size: number, font: Font = 'normal'): string => {
    if (width <= 0) return ''
    if (measure(value, size, font) <= width) return value
    let cut = value
    while (cut.length > 1 && measure(`${cut}...`, size, font) > width) cut = cut.slice(0, -1)
    return `${cut.trimEnd()}...`
  }
  const wrap = (value: string, width: number, size: number, font: Font = 'normal'): string[] => {
    const lines: string[] = []
    let current = ''
    for (const word of value.split(/\s+/).filter(Boolean)) {
      const next = current ? `${current} ${word}` : word
      if (current && measure(next, size, font) > width) {
        lines.push(current)
        current = word
      } else {
        current = next
      }
    }
    if (current) lines.push(current)
    return lines
  }
  const imageBox = (data: string, slot: Rect): Rect => {
    let natural = { width: 0, height: 0 }
    try {
      const properties = doc.getImageProperties(data)
      natural = { width: properties.width, height: properties.height }
    } catch {
      // Unknown size: the logo fills its slot.
    }
    return fitLogo(slot, natural.width, natural.height)
  }
  const placeImage = (data: string, slot: Rect, into: (op: PdfOp) => void = push) => {
    const box = imageBox(data, slot)
    into({ kind: 'image', data, x: box.x, y: box.y, width: box.width, height: box.height })
  }
  const ensure = (needed: number) => {
    if (y + needed <= bottomLimit) return
    pages.push([])
    // A continuation page starts with a quiet header line (team names and date only).
    text(fit(`${model.home.name} v ${model.away.name} · ${model.dateLabel}`, contentW, type.small), left, margin + 3, type.small, MUTED)
    line(left, margin + 5, right, RULE_STRONG, 0.2)
    y = margin + 10
  }

  // ---- Header ----
  const hasHeaderLogos = layout.club !== null || layout.league !== null
  const headerBottom = hasHeaderLogos ? margin + layout.headerText.height : margin + (compact ? 9 : 12)
  const bandBottom = headerBottom + margin * 0.6
  const clubBand = options.template === 'CLUB'
  const headTextColour = clubBand ? onClub : INK
  const headMuted: Rgb = clubBand ? onClub : MUTED
  if (clubBand) fillRect(0, 0, pageW, bandBottom, club)
  for (const [rect, data] of [
    [layout.club, clubImage],
    [layout.league, leagueImage],
  ] as const) {
    if (!rect || !data) continue
    if (clubBand) fillRect(rect.x - 0.8, rect.y - 0.8, rect.width + 1.6, rect.height + 1.6, BACKING, 2)
    placeImage(data, rect)
  }
  const title = model.clubName?.trim() || `${model.home.name} v ${model.away.name}`
  const subtitle = [model.leagueName, model.dateLabel, model.venue].filter(Boolean).join(' · ')
  const headRect = layout.headerText
  text(fit(title, headRect.width, type.title, 'bold'), headRect.x, margin + type.title * MM_PER_PT + 1.2, type.title, headTextColour, 'bold')
  let subtitleY = margin + type.title * MM_PER_PT + 1.2 + type.subtitle * MM_PER_PT + 1.6
  for (const part of wrap(subtitle, headRect.width, type.subtitle).slice(0, 2)) {
    text(part, headRect.x, subtitleY, type.subtitle, headMuted)
    subtitleY += type.subtitle * MM_PER_PT + 1
  }
  if (!clubBand) line(left, bandBottom, right, compact ? club : INK, compact ? 0.5 : 0.7)
  y = bandBottom + type.gap + 1

  // ---- Result ----
  const resultLines = wrap(model.resultLine, contentW - 4, type.result, 'bold')
  const resultHeight = resultLines.length * (type.result * MM_PER_PT + 1.2)
  ensure(resultHeight + 4)
  if (options.template !== 'CLASSIC') fillRect(left, y - 0.5, 1.2, resultHeight, club)
  for (const part of resultLines) {
    y += type.result * MM_PER_PT + 0.4
    text(part, left + (options.template !== 'CLASSIC' ? 4 : 0), y, type.result, INK, 'bold')
    y += 0.8
  }
  y += 1.5
  if (options.include.toss && model.toss) {
    text(fit(model.toss, contentW, type.body), left, y + type.body * MM_PER_PT, type.body, MUTED)
    y += type.body * MM_PER_PT + 2
  }
  y += type.gap - 1

  // ---- Tables ----
  const rowText = (columns: Column[], widths: number[], cells: string[], baseline: number, size: number, colour: Rgb, forceBold = false) => {
    let x = left
    columns.forEach((column, index) => {
      const width = widths[index]
      const font: Font = forceBold || column.bold ? 'bold' : 'normal'
      const cell = fit(cells[index], width - 2, size, font)
      text(cell, column.align === 'right' ? x + width - 1 : x + 1, baseline, size, colour, font, column.align)
      x += width
    })
  }
  const table = (columns: Column[], rows: string[][], headerColour: Rgb) => {
    const fixed = columns.reduce((sum, column) => sum + (column.width ?? 0), 0)
    const widths = columns.map((column) => column.width ?? contentW - fixed)
    const headerH = type.row - 0.4
    ensure(headerH + type.row)
    rowText(columns, widths, columns.map((column) => (column.title.length > 2 ? column.title.toUpperCase() : column.title)), y + headerH * 0.7, type.small - 0.5, headerColour, true)
    y += headerH
    line(left, y, right, RULE_STRONG, 0.2)
    for (const cells of rows) {
      ensure(type.row)
      rowText(columns, widths, cells, y + type.row * 0.7, type.body, INK)
      y += type.row
      line(left, y, right, RULE, 0.15)
    }
    y += 1.5
  }

  const teamOf = (name: string): ShareTeam | undefined => [model.home, model.away].find((team) => team.name === name)
  const teamHeading = (team: ShareTeam | undefined, name: string, score: string) => {
    const slot = type.heading * MM_PER_PT + 3
    ensure(slot + type.row * 3)
    const top = y
    if (options.logos.teams) {
      const rect: Rect = { x: left, y: top, width: slot, height: slot }
      const data = imageOf(team?.logoUrl ?? null)
      if (data) {
        placeImage(data, rect)
      } else {
        fillRect(rect.x, rect.y, rect.width, rect.height, club, slot / 2)
        text(name.charAt(0).toUpperCase() || '?', rect.x + slot / 2, rect.y + slot / 2 + 1.3, type.small + 1, onClub, 'bold', 'center')
      }
    }
    const textX = options.logos.teams ? left + slot + 2 : left
    const baseline = top + slot / 2 + type.heading * MM_PER_PT * 0.35
    const scoreW = measure(score, type.heading, 'bold')
    text(fit(name, right - textX - scoreW - 3, type.heading, 'bold'), textX, baseline, type.heading, INK, 'bold')
    text(score, right, baseline, type.heading, INK, 'bold', 'right')
    y = top + slot + 1
    line(left, y, right, compact ? club : INK, compact ? 0.3 : 0.4)
    y += 1.5
  }

  const battingColumns: Column[] = [
    { title: 'Batter', width: 46, align: 'left', bold: true },
    { title: 'How out', align: 'left' },
    { title: 'R', width: 11, align: 'right', bold: true },
    { title: 'B', width: 11, align: 'right' },
    { title: '4s', width: 11, align: 'right' },
    { title: '6s', width: 11, align: 'right' },
  ]
  const battingCells = (row: ShareBattingRow): string[] =>
    row.didNotBat
      ? [row.name, row.howOut || 'did not bat', '', '', '', '']
      : [row.name, row.howOut, display(row.runs), display(row.balls), display(row.fours), display(row.sixes)]
  const bowlingColumns: Column[] = [
    { title: 'Bowler', align: 'left', bold: true },
    { title: 'O', width: 14, align: 'right' },
    { title: 'M', width: 14, align: 'right' },
    { title: 'R', width: 14, align: 'right' },
    { title: 'W', width: 14, align: 'right', bold: true },
  ]
  const bowlingCells = (row: ShareBowlingRow): string[] => [row.name, row.overs, display(row.maidens), display(row.runs), display(row.wickets)]

  const drawInnings = (innings: ShareInnings) => {
    teamHeading(teamOf(innings.battingTeam), innings.battingTeam, innings.scoreText)
    if (options.include.batting && innings.batting.length > 0) {
      table(battingColumns, innings.batting.map(battingCells), MUTED)
    }
    if (options.include.extras && innings.extras) {
      ensure(type.row)
      text(fit(innings.extras.text, contentW, type.body), left + 1, y + type.row * 0.6, type.body, MUTED)
      y += type.row + 1
    }
    if (options.include.bowling && innings.bowling.length > 0) {
      ensure(type.row * 3)
      text(`Bowling: ${innings.bowlingTeam}`, left + 1, y + type.body * MM_PER_PT, type.body, MUTED, 'bold')
      y += type.body * MM_PER_PT + 1.5
      table(bowlingColumns, innings.bowling.map(bowlingCells), MUTED)
    }
    y += type.gap
  }

  if (model.innings.length > 0) {
    model.innings.forEach(drawInnings)
  } else {
    // A summary-only result: both scores, no tables.
    for (const team of [model.home, model.away]) {
      teamHeading(team, team.name, team.scoreText)
      y += type.gap - 2
    }
  }

  if (options.include.playerOfTheMatch && model.playerOfTheMatch) {
    ensure(type.row + 2)
    text(fit(`Player of the match: ${model.playerOfTheMatch.name}`, contentW, type.body + 1), left, y + type.row * 0.7, type.body + 1, INK, 'bold')
    y += type.row + 2
  }

  // ---- Footer on every page: the sponsor strip, then the page number and the Footer line ----
  const total = pages.length
  const website = options.footerLine && options.clubWebsite?.trim() ? websiteText(options.clubWebsite) : null
  const drawFooter = (index: number) => {
    const ops = pages[index]
    const add = (op: PdfOp) => ops.push(op)
    if (layout.sponsorLabel && sponsorImages.length > 0) {
      add({ kind: 'line', x1: left, y1: layout.sponsorLabel.y - 0.5, x2: right, y2: layout.sponsorLabel.y - 0.5, colour: RULE, lineWidth: 0.2 })
      add({
        kind: 'text',
        text: SPONSOR_LABEL,
        x: left,
        y: layout.sponsorLabel.y + layout.sponsorLabel.height * 0.7,
        align: 'left',
        font: 'normal',
        size: type.small + 0.5,
        colour: MUTED,
      })
      sponsorImages.forEach((data, position) => placeImage(data, layout.sponsors[position], add))
    }
    // The page number stays on every PDF; the web address and platform credit go with the Footer line switch.
    const footer = [`Page ${index + 1} of ${total}`, website, options.footerLine ? PLATFORM_CREDIT : null].filter(Boolean).join(' · ')
    add({
      kind: 'text',
      text: footer,
      x: left,
      y: footerRect.y + footerRect.height * 0.65,
      align: 'left',
      font: 'normal',
      size: type.small + 0.5,
      colour: MUTED,
    })
  }
  pages.forEach((_, index) => drawFooter(index))

  // ---- Replay into jsPDF; an image jsPDF cannot embed is dropped from the preview too ----
  const previewPages: PdfOp[][] = []
  pages.forEach((ops, index) => {
    if (index > 0) doc.addPage()
    const kept: PdfOp[] = []
    for (const op of ops) {
      if (op.kind === 'rect') {
        doc.setFillColor(...op.fill)
        if (op.radius > 0) doc.roundedRect(op.x, op.y, op.width, op.height, op.radius, op.radius, 'F')
        else doc.rect(op.x, op.y, op.width, op.height, 'F')
      } else if (op.kind === 'line') {
        doc.setDrawColor(...op.colour)
        doc.setLineWidth(op.lineWidth)
        doc.line(op.x1, op.y1, op.x2, op.y2)
      } else if (op.kind === 'text') {
        doc.setTextColor(...op.colour)
        doc.setFont('helvetica', op.font)
        doc.setFontSize(op.size)
        doc.text(op.text, op.x, op.y, { align: op.align })
      } else {
        try {
          doc.addImage(op.data, imageFormat(op.data), op.x, op.y, op.width, op.height)
        } catch {
          // A broken or unsupported image never blocks the rest of the PDF.
          continue
        }
      }
      kept.push(op)
    }
    previewPages.push(kept)
  })

  const blob = doc.output('blob')
  return { blob, url: URL.createObjectURL(blob), pageCount: pages.length, pages: previewPages }
}
