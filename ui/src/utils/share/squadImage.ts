import { fitLogo, layoutLogos, MAX_SHARE_SPONSORS } from './logoLayout'
import type { Rect } from './logoLayout'
import { MATCH_IMAGE_HEIGHTS, drawCrest, drawText, imageFor, matchPalette, roundedRect } from './matchImage'
import type { Ctx, Palette } from './matchImage'
import type { ResultImageColour } from './resultImage'
import type { ImageSize, ImageTemplate } from './shareChoices'
import { BRAND } from '../../brandTokens'

// The squad poster: a team's whole squad for a season, not tied to any match. A grid of round player pictures with the name under each
// (shirt number and captain or keeper mark on the picture), or a list. One Canvas2D function for the preview and the file, drawn with the
// same palette, logo slots, sponsor strip and footer as the match posters (utils/share/matchImage.ts).

export interface SquadSharePlayer {
  key: string
  // Already through shareName rules by the caller: these are what is drawn.
  firstName: string
  lastName: string
  shirt: number | null
  captain: boolean
  keeper: boolean
  photoUrl: string | null
}

export interface SquadShareModel {
  teamName: string
  teamLogoUrl: string | null
  seasonLabel: string | null
  players: SquadSharePlayer[]
}

export type SquadLayout = 'GRID' | 'LIST'

export interface SquadImageOptions {
  size: ImageSize
  template: ImageTemplate
  colour: ResultImageColour
  layout: SquadLayout
  include: { shirtNumbers: boolean; marks: boolean; playerPictures: boolean }
  logos: { clubUrl: string | null; teamAffiliationUrl: string | null; teamLogo: boolean; sponsorUrls: string[] }
  // The Text Size step as a factor (1 = Auto).
  textScale?: number
  images: Map<string, HTMLImageElement | null>
  clubWebsite?: string | null
  footerLine: boolean
}

const WHITE = 'rgb(255, 255, 255)'
const PLATFORM_CREDIT = 'Generated by Cricket Legend'
const SPONSOR_LABEL = 'Proudly sponsored by'

export const squadImageSize = (size: ImageSize): { width: number; height: number } => ({ width: 1080, height: MATCH_IMAGE_HEIGHTS[size] })

const fullName = (player: SquadSharePlayer): string => `${player.firstName} ${player.lastName}`.trim()

// A round picture (or initial tile) of a player with the shirt number on its top left and the captain or keeper mark at its bottom right.
function drawPlayerPicture(ctx: Ctx, player: SquadSharePlayer, centreX: number, centreY: number, radius: number, options: SquadImageOptions, palette: Palette): void {
  const image = imageFor(options.images, player.photoUrl)
  drawCrest(ctx, centreX, centreY, radius, fullName(player), image, palette)
  if (options.include.shirtNumbers && player.shirt !== null) {
    const badge = radius * 0.36
    ctx.fillStyle = palette.accent
    ctx.beginPath()
    ctx.arc(centreX - radius * 0.72, centreY - radius * 0.72, badge, 0, Math.PI * 2)
    ctx.fill()
    drawText(ctx, String(player.shirt), centreX - radius * 0.72, centreY - radius * 0.72, { size: badge * 1.05, colour: BRAND.ink, weight: 700, align: 'center', maxWidth: badge * 1.7 })
  }
  const mark = options.include.marks ? [player.captain ? 'C' : '', player.keeper ? 'WK' : ''].filter(Boolean).join(' ') : ''
  if (mark) {
    const height = radius * 0.5
    const width = Math.max(height, radius * 0.34 * mark.length + radius * 0.3)
    roundedRect(ctx, { x: centreX + radius * 0.78 - width / 2, y: centreY + radius * 0.78 - height / 2, width, height }, height / 2, palette.chip)
    drawText(ctx, mark, centreX + radius * 0.78, centreY + radius * 0.78, { size: height * 0.62, colour: palette.chipText, weight: 700, align: 'center' })
  }
}

// A number on a plain accent disc, for a grid without pictures.
function drawNumberDisc(ctx: Ctx, player: SquadSharePlayer, centreX: number, centreY: number, radius: number, palette: Palette): void {
  ctx.fillStyle = palette.accent
  ctx.beginPath()
  ctx.arc(centreX, centreY, radius, 0, Math.PI * 2)
  ctx.fill()
  drawText(ctx, player.shirt !== null ? String(player.shirt) : (fullName(player)[0] ?? '?').toUpperCase(), centreX, centreY, { size: radius * 0.95, colour: BRAND.ink, weight: 700, align: 'center', maxWidth: radius * 1.7 })
}

function drawGrid(ctx: Ctx, model: SquadShareModel, options: SquadImageOptions, palette: Palette, area: Rect, k: number): void {
  const count = model.players.length
  const pictures = options.include.playerPictures
  // The column count that gives the biggest pictures in the room there is.
  let best = { columns: 2, diameter: 0 }
  for (let columns = 2; columns <= 7; columns += 1) {
    const rows = Math.ceil(count / columns)
    const cellW = area.width / columns
    const cellH = area.height / rows
    const diameter = Math.min(cellW * 0.8, cellH * 0.6)
    if (diameter > best.diameter) best = { columns, diameter }
  }
  const { columns, diameter } = best
  const rows = Math.ceil(count / columns)
  const cellW = area.width / columns
  const cellH = area.height / rows
  const radius = diameter / 2
  const scale = Math.min(Math.max(1, options.textScale ?? 1), 1.4)
  const nameSize = Math.min(radius * 0.4 * scale, cellH * 0.17, 40 * k * scale)
  model.players.forEach((player, index) => {
    const column = index % columns
    const row = Math.floor(index / columns)
    const centreX = area.x + column * cellW + cellW / 2
    const top = area.y + row * cellH + (cellH - (diameter + nameSize * 3.1)) / 2
    const centreY = top + radius
    if (pictures) drawPlayerPicture(ctx, player, centreX, centreY, radius, options, palette)
    else drawNumberDisc(ctx, player, centreX, centreY, radius, palette)
    drawText(ctx, player.firstName, centreX, centreY + radius + nameSize * 0.95, { size: nameSize * 0.82, colour: palette.muted, align: 'center', maxWidth: cellW * 0.94 })
    drawText(ctx, player.lastName.toUpperCase(), centreX, centreY + radius + nameSize * 2.05, { size: nameSize, colour: palette.text, weight: 700, align: 'center', maxWidth: cellW * 0.94 })
    if (!pictures && options.include.marks && (player.captain || player.keeper)) {
      drawText(ctx, [player.captain ? 'C' : '', player.keeper ? 'WK' : ''].filter(Boolean).join(' '), centreX, centreY + radius + nameSize * 3.05, { size: nameSize * 0.7, colour: palette.accent, weight: 700, align: 'center' })
    }
  })
}

function drawList(ctx: Ctx, model: SquadShareModel, options: SquadImageOptions, palette: Palette, area: Rect, k: number): void {
  const count = model.players.length
  const pictures = options.include.playerPictures
  const columns: 1 | 2 = count > 8 ? 2 : 1
  const perColumn = Math.ceil(count / columns)
  const scale = Math.min(Math.max(1, options.textScale ?? 1), 1.4)
  const rowH = Math.min(area.height / perColumn, 84 * k * scale)
  const gap = 28 * k
  const columnW = (area.width - (columns - 1) * gap) / columns
  const size = rowH * 0.42
  model.players.forEach((player, index) => {
    const column = Math.floor(index / perColumn)
    const row = index % perColumn
    const x = area.x + column * (columnW + gap)
    const centreY = area.y + row * rowH + rowH / 2
    const radius = rowH * 0.4
    let left = x
    if (options.include.shirtNumbers) {
      drawText(ctx, player.shirt !== null ? String(player.shirt) : '', x, centreY, { size, colour: palette.accent, weight: 700, maxWidth: size * 1.7 })
      left = x + size * 1.9
    }
    if (pictures) {
      drawPlayerPicture(ctx, { ...player, shirt: null, captain: false, keeper: false }, left + radius, centreY, radius, { ...options, include: { ...options.include, shirtNumbers: false, marks: false } }, palette)
      left += radius * 2 + size * 0.6
    }
    const marks = options.include.marks ? `${player.captain ? ' (C)' : ''}${player.keeper ? ' (WK)' : ''}` : ''
    drawText(ctx, `${fullName(player)}${marks}`, left, centreY, { size, colour: palette.text, weight: 500, maxWidth: x + columnW - left })
  })
}

export function drawSquadImage(target: HTMLCanvasElement | CanvasRenderingContext2D, model: SquadShareModel, options: SquadImageOptions): void {
  const { width, height } = squadImageSize(options.size)
  let ctx: Ctx | null
  if ('getContext' in target) {
    target.width = width
    target.height = height
    ctx = target.getContext('2d')
  } else {
    ctx = target
  }
  if (!ctx) throw new Error('The image could not be drawn in this browser.')
  const palette = matchPalette(options.template, options.colour)
  const unit = Math.min(width, height)
  const k = unit / 1080

  const gradient = ctx.createLinearGradient(0, 0, width * 0.3, height)
  gradient.addColorStop(0, palette.background[0])
  gradient.addColorStop(1, palette.background[1])
  ctx.fillStyle = gradient
  ctx.fillRect(0, 0, width, height)

  const clubImage = imageFor(options.images, options.logos.clubUrl)
  const affiliationImage = imageFor(options.images, options.logos.teamAffiliationUrl)
  const sponsorImages = options.logos.sponsorUrls
    .slice(0, MAX_SHARE_SPONSORS)
    .map((url) => imageFor(options.images, url))
    .filter((image): image is HTMLImageElement => image !== null)
  const layout = layoutLogos({
    format: 'IMAGE',
    width,
    height,
    club: clubImage !== null,
    league: false,
    teamAffiliation: affiliationImage !== null,
    leagueAffiliation: false,
    teamLogos: false,
    sponsors: sponsorImages.length,
    footerLine: options.footerLine,
  })
  const margin = layout.margin

  const drawSlotLogo = (slot: Rect | null, image: HTMLImageElement | null) => {
    if (!slot || !image) return
    roundedRect(ctx, slot, Math.min(slot.width, slot.height) * 0.12, WHITE)
    const fit = fitLogo({ x: slot.x + slot.width * 0.08, y: slot.y + slot.height * 0.08, width: slot.width * 0.84, height: slot.height * 0.84 }, image.naturalWidth || image.width, image.naturalHeight || image.height)
    ctx.drawImage(image, fit.x, fit.y, fit.width, fit.height)
  }
  drawSlotLogo(layout.club, clubImage)
  drawSlotLogo(layout.teamAffiliation, affiliationImage)
  const headerHeight = layout.club?.height ?? layout.teamAffiliation?.height ?? 0
  drawText(ctx, 'SQUAD', layout.headerText.x + layout.headerText.width / 2, margin + (headerHeight || 40 * k) / 2, { size: 28 * k, colour: palette.muted, weight: 700, align: 'center', maxWidth: layout.headerText.width })

  // The title row: the team's crest (when on) and its name, then the season and the number of players.
  const title = { x: margin, y: layout.homeName.y, width: width - margin * 2, height: Math.max(layout.homeName.height, 70 * k) }
  let nameX = title.x
  if (options.logos.teamLogo) {
    const radius = title.height * 0.5
    drawCrest(ctx, title.x + radius, title.y + title.height / 2, radius, model.teamName, imageFor(options.images, model.teamLogoUrl), palette)
    nameX = title.x + radius * 2 + 22 * k
  }
  drawText(ctx, model.teamName.toUpperCase(), nameX, title.y + title.height / 2, { size: title.height * 0.62, colour: palette.text, weight: 700, maxWidth: title.x + title.width - nameX })
  const sub = [model.seasonLabel, `${model.players.length} ${model.players.length === 1 ? 'player' : 'players'}`].filter(Boolean).join(' · ')
  const subY = title.y + title.height + 22 * k
  drawText(ctx, sub, margin, subY, { size: 28 * k, colour: palette.muted, maxWidth: width - margin * 2 })

  const top = subY + 30 * k
  const bottom = layout.content.y + layout.content.height
  const area: Rect = { x: margin, y: top, width: width - margin * 2, height: Math.max(0, bottom - top) }
  if (model.players.length === 0) {
    drawText(ctx, 'No players in this squad yet', width / 2, area.y + area.height / 2, { size: 36 * k, colour: palette.muted, align: 'center' })
  } else if (options.layout === 'LIST') {
    drawList(ctx, model, options, palette, area, k)
  } else {
    drawGrid(ctx, model, options, palette, area, k)
  }

  if (layout.sponsorLabel) {
    drawText(ctx, SPONSOR_LABEL, width / 2, layout.sponsorLabel.y + layout.sponsorLabel.height / 2, { size: 22 * k, colour: palette.muted, align: 'center' })
    sponsorImages.forEach((image, index) => {
      const slot = layout.sponsors[index]
      if (!slot) return
      roundedRect(ctx, slot, Math.min(slot.width, slot.height) * 0.1, WHITE)
      const fit = fitLogo({ x: slot.x + 6 * k, y: slot.y + 6 * k, width: slot.width - 12 * k, height: slot.height - 12 * k }, image.naturalWidth || image.width, image.naturalHeight || image.height)
      ctx.drawImage(image, fit.x, fit.y, fit.width, fit.height)
    })
  }
  if (layout.footerText) {
    const site = options.clubWebsite?.trim().replace(/^https?:\/\//i, '').replace(/\/$/, '')
    const middle = layout.footerText.y + layout.footerText.height / 2
    if (site) drawText(ctx, site, layout.footerText.x, middle, { size: 22 * k, colour: palette.muted, maxWidth: layout.footerText.width * 0.5 })
    drawText(ctx, PLATFORM_CREDIT, layout.footerText.x + layout.footerText.width, middle, { size: 22 * k, colour: palette.muted, align: 'right' })
  }
}

export function generateSquadImage(model: SquadShareModel, options: SquadImageOptions): Promise<Blob> {
  const canvas = document.createElement('canvas')
  drawSquadImage(canvas, model, options)
  return new Promise((resolve, reject) => {
    canvas.toBlob((blob) => (blob ? resolve(blob) : reject(new Error('The image could not be created.'))), 'image/png')
  })
}
