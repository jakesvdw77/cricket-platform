import { jsPDF } from 'jspdf'
import { fitLogo, layoutLogos, MAX_SHARE_SPONSORS } from './logoLayout'
import type { Rect } from './logoLayout'
import { LEAGUE_CONTENT_LABELS } from './leagueShareFormats'
import { PDF_PAGE_HEIGHT, PDF_PAGE_WIDTH } from './resultPdf'
import type { PdfOp, ResultPdfLogos, ResultPdfOutput } from './resultPdf'
import { readableOn } from './resultImage'
import type { ResultImageColour } from './resultImage'
import type { LeagueShareModel, LeagueShareSide } from './shareLeagueData'

// docs/specs/122-league-sharing.md (Format screens, PDF): one A4 document with a section per ticked content, in the
// standard order. Mirrors resultPdf.ts: the page is laid out into PdfOp lists (the very type the result PDF and its
// canvas preview use, so drawResultPdfPage previews it), then replayed into jsPDF. Every name comes from the
// LeagueShareModel (already in the shared name form). Document metadata carries league, season and club names only.

type Rgb = [number, number, number]
type Align = 'left' | 'right' | 'center'
type Font = 'normal' | 'bold' | 'italic'

const WHITE: Rgb = [255, 255, 255]
const INK: Rgb = [20, 35, 28] // theme.palette.text.primary
const MUTED: Rgb = [82, 101, 92] // theme.palette.text.secondary
const RULE: Rgb = [229, 235, 231]
const RULE_STRONG: Rgb = [154, 169, 161]
const ON_CLUB_WHITE = '#ffffff'
const ON_CLUB_INK = '#14231c'
const PLATFORM_CREDIT = 'Generated by Cricket Legend'
const SPONSOR_LABEL = 'Proudly sponsored by'
const MM_PER_PT = 25.4 / 72
const TYPE = { title: 15, subtitle: 8.5, heading: 10, body: 8.5, small: 7, row: 5.6, gap: 5 }

export interface LeaguePdfOptions {
  colour: ResultImageColour
  logos: ResultPdfLogos
  clubWebsite: string | null
  footerLine: boolean
  // Results as the result line (true) or as scores only (false).
  resultLine: boolean
}

function hexToRgb(hex: string, fallback: Rgb): Rgb {
  const match = /^#?([0-9a-f]{3}|[0-9a-f]{6})$/i.exec(hex.trim())
  if (!match) return fallback
  const digits = match[1].length === 3 ? match[1].replace(/./g, '$&$&') : match[1]
  return [parseInt(digits.slice(0, 2), 16), parseInt(digits.slice(2, 4), 16), parseInt(digits.slice(4, 6), 16)]
}

async function loadImageBase64(url: string): Promise<string | null> {
  try {
    const response = await fetch(url)
    if (!response.ok) return null
    const blob = await response.blob()
    return await new Promise<string>((resolve, reject) => {
      const reader = new FileReader()
      reader.onload = () => resolve(reader.result as string)
      reader.onerror = () => reject(reader.error)
      reader.readAsDataURL(blob)
    })
  } catch {
    return null
  }
}

const imageFormat = (data: string): string => (/^data:image\/jpe?g/i.test(data) ? 'JPEG' : 'PNG')
const websiteText = (website: string): string => website.trim().replace(/^https?:\/\//i, '').replace(/\/$/, '')

export async function generateLeaguePdf(model: LeagueShareModel, options: LeaguePdfOptions): Promise<ResultPdfOutput> {
  const club = hexToRgb(options.colour.main, INK)
  const onClub = hexToRgb(readableOn([options.colour.main], [options.colour.contrastText, ON_CLUB_WHITE, ON_CLUB_INK]), WHITE)
  const showTeamLogos = options.logos.teams && (model.contents.includes('TEAMS') || model.contents.includes('SCHEDULE'))

  const sponsorUrls = options.logos.sponsorUrls.slice(0, MAX_SHARE_SPONSORS)
  const teamUrls = showTeamLogos
    ? [
        ...model.teams.map((team) => team.logoUrl),
        ...model.schedule.flatMap((fixture) => [fixture.home.logoUrl, fixture.away.logoUrl]),
      ]
    : []
  const wanted = [options.logos.clubUrl, options.logos.leagueUrl, ...sponsorUrls, ...teamUrls].filter((url): url is string => Boolean(url))
  const loaded = new Map<string, string | null>(
    await Promise.all([...new Set(wanted)].map(async (url) => [url, await loadImageBase64(url)] as const)),
  )
  const imageOf = (url: string | null): string | null => (url ? (loaded.get(url) ?? null) : null)
  const clubImage = imageOf(options.logos.clubUrl)
  const leagueImage = imageOf(options.logos.leagueUrl)
  const sponsorImages = sponsorUrls.map(imageOf).filter((data): data is string => data !== null)

  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' })
  doc.setProperties({
    title: model.title,
    subject: [model.league.name, model.season?.label].filter(Boolean).join(', ') || 'League',
    author: model.clubName || 'Cricket Legend',
    creator: 'Cricket Legend',
  })

  const pageW = PDF_PAGE_WIDTH
  const pageH = PDF_PAGE_HEIGHT
  const layout = layoutLogos({
    format: 'PDF',
    width: pageW,
    height: pageH,
    club: clubImage !== null,
    league: leagueImage !== null,
    teamLogos: false,
    sponsors: sponsorImages.length,
    footerLine: true,
  })
  const margin = layout.margin
  const left = margin
  const right = pageW - margin
  const contentW = right - left
  const footerRect = layout.footerText as Rect
  const bottomLimit = (layout.sponsorLabel ? layout.sponsorLabel.y : footerRect.y) - 3

  const pages: PdfOp[][] = [[]]
  let y = 0
  const push = (op: PdfOp) => {
    pages[pages.length - 1].push(op)
  }
  const fillRect = (x: number, top: number, width: number, height: number, colour: Rgb, radius = 0) =>
    push({ kind: 'rect', x, y: top, width, height, radius, fill: colour })
  const line = (x1: number, y1: number, x2: number, colour: Rgb, lineWidth = 0.2) =>
    push({ kind: 'line', x1, y1, x2, y2: y1, colour, lineWidth })
  const text = (value: string, x: number, baseline: number, size: number, colour: Rgb, font: Font = 'normal', align: Align = 'left') => {
    if (value) push({ kind: 'text', text: value, x, y: baseline, align, font, size, colour })
  }
  const measure = (value: string, size: number, font: Font = 'normal'): number => {
    doc.setFont('helvetica', font)
    doc.setFontSize(size)
    return doc.getTextWidth(value)
  }
  const fit = (value: string, width: number, size: number, font: Font = 'normal'): string => {
    if (width <= 0) return ''
    if (measure(value, size, font) <= width) return value
    let cut = value
    while (cut.length > 1 && measure(`${cut}...`, size, font) > width) cut = cut.slice(0, -1)
    return `${cut.trimEnd()}...`
  }
  const wrap = (value: string, width: number, size: number, font: Font = 'normal'): string[] => {
    const lines: string[] = []
    let current = ''
    for (const word of value.split(/\s+/).filter(Boolean)) {
      const next = current ? `${current} ${word}` : word
      if (current && measure(next, size, font) > width) {
        lines.push(current)
        current = word
      } else {
        current = next
      }
    }
    if (current) lines.push(current)
    return lines
  }
  const placeImage = (data: string, slot: Rect, into: (op: PdfOp) => void = push) => {
    let natural = { width: 0, height: 0 }
    try {
      const properties = doc.getImageProperties(data)
      natural = { width: properties.width, height: properties.height }
    } catch {
      // Unknown size: the logo fills its slot.
    }
    const box = fitLogo(slot, natural.width, natural.height)
    into({ kind: 'image', data, x: box.x, y: box.y, width: box.width, height: box.height })
  }
  const ensure = (needed: number) => {
    if (y + needed <= bottomLimit) return
    pages.push([])
    text(fit(model.title, contentW, TYPE.small), left, margin + 3, TYPE.small, MUTED)
    line(left, margin + 5, right, RULE_STRONG, 0.2)
    y = margin + 10
  }
  const lineHeight = TYPE.body * MM_PER_PT + 1.4

  // ---- Header (club colour band) ----
  const hasHeaderLogos = layout.club !== null || layout.league !== null
  const headerBottom = hasHeaderLogos ? margin + layout.headerText.height : margin + 12
  const bandBottom = headerBottom + margin * 0.6
  fillRect(0, 0, pageW, bandBottom, club)
  for (const [rect, data] of [
    [layout.club, clubImage],
    [layout.league, leagueImage],
  ] as const) {
    if (!rect || !data) continue
    fillRect(rect.x - 0.8, rect.y - 0.8, rect.width + 1.6, rect.height + 1.6, WHITE, 2)
    placeImage(data, rect)
  }
  const headRect = layout.headerText
  const titleBase = margin + TYPE.title * MM_PER_PT + 1.2
  text(fit(model.league.name, headRect.width, TYPE.title, 'bold'), headRect.x, titleBase, TYPE.title, onClub, 'bold')
  const subtitle = [model.season?.label, model.clubName].filter(Boolean).join(' · ')
  text(fit(subtitle, headRect.width, TYPE.subtitle), headRect.x, titleBase + TYPE.subtitle * MM_PER_PT + 1.6, TYPE.subtitle, onClub)
  y = bandBottom + TYPE.gap + 1

  const sectionHeading = (label: string) => {
    ensure(TYPE.row * 3)
    fillRect(left, y, 1.2, TYPE.heading * MM_PER_PT + 1.5, club)
    text(label, left + 4, y + TYPE.heading * MM_PER_PT + 0.4, TYPE.heading, INK, 'bold')
    y += TYPE.heading * MM_PER_PT + 3.5
  }
  const paragraph = (value: string, indent = 0, colour: Rgb = INK, font: Font = 'normal') => {
    for (const part of wrap(value, contentW - indent, TYPE.body, font)) {
      ensure(lineHeight)
      y += lineHeight - 0.6
      text(part, left + indent, y, TYPE.body, colour, font)
      y += 0.6
    }
  }
  const labelled = (label: string, value: string, labelW = 44) => {
    const parts = wrap(value, contentW - labelW, TYPE.body)
    ensure(lineHeight * Math.max(1, parts.length))
    parts.forEach((part, index) => {
      y += lineHeight - 0.6
      if (index === 0) text(label, left, y, TYPE.body, MUTED, 'bold')
      text(part, left + labelW, y, TYPE.body, INK)
      y += 0.6
    })
    if (parts.length === 0) y += lineHeight
  }
  const sideLogo = (side: LeagueShareSide, x: number, top: number, size: number) => {
    const data = imageOf(side.logoUrl)
    if (data) {
      placeImage(data, { x, y: top, width: size, height: size })
    } else {
      fillRect(x, top, size, size, RULE, 1)
      text(side.name.charAt(0).toUpperCase() || '?', x + size / 2, top + size * 0.7, TYPE.small, INK, 'bold', 'center')
    }
  }
  const rowRule = () => {
    line(left, y + 0.6, right, RULE, 0.2)
    y += 1.6
  }

  // ---- One section per ticked content, standard order ----
  const logoSize = 4.6
  for (const content of model.contents) {
    if (content === 'DETAILS') {
      sectionHeading(LEAGUE_CONTENT_LABELS.DETAILS)
      const { league } = model
      if (league.formatLabel) labelled('Format', league.formatLabel)
      if (league.ageLabel) labelled('Ages', league.ageLabel)
      if (league.matchCount > 0) labelled('Matches', String(league.matchCount))
      if (league.website) labelled('Website', league.website)
      if (league.phone) labelled('Phone', league.phone)
      if (league.email) labelled('Email', league.email)
      for (const contact of league.contacts) {
        labelled(contact.role, [contact.name, contact.phone, contact.email].filter(Boolean).join(', '))
      }
    } else if (content === 'CONDITIONS') {
      sectionHeading(LEAGUE_CONTENT_LABELS.CONDITIONS)
      if (model.conditions.length === 0) paragraph('No playing conditions set for this season yet.', 0, MUTED, 'italic')
      for (const section of model.conditions) {
        ensure(lineHeight * 2)
        paragraph(section.heading, 0, INK, 'bold')
        for (const row of section.rows) labelled(row.label, row.value)
        y += 1.5
      }
    } else if (content === 'TEAMS') {
      sectionHeading(LEAGUE_CONTENT_LABELS.TEAMS)
      for (const team of model.teams) {
        ensure(logoSize + 2)
        const textX = showTeamLogos ? left + logoSize + 3 : left
        if (showTeamLogos) sideLogo({ name: team.name, logoUrl: team.logoUrl, own: team.own }, left, y, logoSize)
        const base = y + logoSize * 0.7
        text(fit(team.name, contentW - (textX - left) - 30, TYPE.body, team.own ? 'bold' : 'normal'), textX, base, TYPE.body, INK, team.own ? 'bold' : 'normal')
        if (team.own) text('Our team', right, base, TYPE.small, MUTED, 'normal', 'right')
        y += logoSize
        rowRule()
      }
    } else if (content === 'SCHEDULE') {
      sectionHeading(LEAGUE_CONTENT_LABELS.SCHEDULE)
      for (const fixture of model.schedule) {
        ensure(logoSize * 2 + 3)
        text(`${fixture.dateLabel}${fixture.timeLabel ? ` ${fixture.timeLabel}` : ''}`, left, y + TYPE.small * MM_PER_PT + 0.4, TYPE.small, MUTED)
        y += TYPE.small * MM_PER_PT + 1.4
        const textX = showTeamLogos ? left + logoSize + 3 : left
        if (showTeamLogos) sideLogo(fixture.home, left, y, logoSize)
        const base = y + logoSize * 0.7
        const names = `${fixture.home.name} v ${fixture.away.name}`
        text(fit(names, contentW - (textX - left), TYPE.body, 'bold'), textX, base, TYPE.body, INK, 'bold')
        y += logoSize
        if (fixture.venue) {
          text(fit(fixture.venue, contentW, TYPE.small), textX, y + TYPE.small * MM_PER_PT + 0.4, TYPE.small, MUTED)
          y += TYPE.small * MM_PER_PT + 1.2
        }
        rowRule()
      }
    } else if (content === 'RESULTS') {
      sectionHeading(LEAGUE_CONTENT_LABELS.RESULTS)
      if (model.results.length === 0) paragraph('No published results for this season yet.', 0, MUTED, 'italic')
      for (const row of model.results) {
        ensure(lineHeight * 3)
        text(row.dateLabel, left, y + TYPE.small * MM_PER_PT + 0.4, TYPE.small, MUTED)
        y += TYPE.small * MM_PER_PT + 1.4
        const scored = row.homeScore && row.awayScore
        const head = scored && !options.resultLine ? `${row.home.name} ${row.homeScore} v ${row.away.name} ${row.awayScore}` : `${row.home.name} v ${row.away.name}`
        paragraph(head, 0, INK, 'bold')
        if (options.resultLine || !scored) paragraph(row.resultLine, 0, MUTED)
        if (options.resultLine && scored) paragraph(`${row.home.name} ${row.homeScore} · ${row.away.name} ${row.awayScore}`, 0, MUTED)
        rowRule()
      }
    } else if (content === 'KEY_DATES') {
      sectionHeading(LEAGUE_CONTENT_LABELS.KEY_DATES)
      if (model.keyDates.length === 0) paragraph('No dates set for this season yet.', 0, MUTED, 'italic')
      for (const date of model.keyDates) labelled(date.label, date.dateLabel, 40)
    }
    y += TYPE.gap
  }

  // ---- Footer on every page ----
  const total = pages.length
  const website = options.footerLine && options.clubWebsite?.trim() ? websiteText(options.clubWebsite) : null
  pages.forEach((ops, index) => {
    const add = (op: PdfOp) => ops.push(op)
    if (layout.sponsorLabel && sponsorImages.length > 0) {
      add({ kind: 'line', x1: left, y1: layout.sponsorLabel.y - 0.5, x2: right, y2: layout.sponsorLabel.y - 0.5, colour: RULE, lineWidth: 0.2 })
      add({
        kind: 'text',
        text: SPONSOR_LABEL,
        x: left,
        y: layout.sponsorLabel.y + layout.sponsorLabel.height * 0.7,
        align: 'left',
        font: 'normal',
        size: TYPE.small + 0.5,
        colour: MUTED,
      })
      sponsorImages.forEach((data, position) => placeImage(data, layout.sponsors[position], add))
    }
    const footer = [`Page ${index + 1} of ${total}`, website, options.footerLine ? PLATFORM_CREDIT : null].filter(Boolean).join(' · ')
    add({
      kind: 'text',
      text: footer,
      x: left,
      y: footerRect.y + footerRect.height * 0.65,
      align: 'left',
      font: 'normal',
      size: TYPE.small + 0.5,
      colour: MUTED,
    })
  })

  // ---- Replay into jsPDF; an image jsPDF cannot embed is dropped from the preview too ----
  const previewPages: PdfOp[][] = []
  pages.forEach((ops, index) => {
    if (index > 0) doc.addPage()
    const kept: PdfOp[] = []
    for (const op of ops) {
      if (op.kind === 'rect') {
        doc.setFillColor(...op.fill)
        if (op.radius > 0) doc.roundedRect(op.x, op.y, op.width, op.height, op.radius, op.radius, 'F')
        else doc.rect(op.x, op.y, op.width, op.height, 'F')
      } else if (op.kind === 'line') {
        doc.setDrawColor(...op.colour)
        doc.setLineWidth(op.lineWidth)
        doc.line(op.x1, op.y1, op.x2, op.y2)
      } else if (op.kind === 'text') {
        doc.setTextColor(...op.colour)
        doc.setFont('helvetica', op.font)
        doc.setFontSize(op.size)
        doc.text(op.text, op.x, op.y, { align: op.align })
      } else {
        try {
          doc.addImage(op.data, imageFormat(op.data), op.x, op.y, op.width, op.height)
        } catch {
          continue
        }
      }
      kept.push(op)
    }
    previewPages.push(kept)
  })

  const blob = doc.output('blob')
  return { blob, url: URL.createObjectURL(blob), pageCount: pages.length, pages: previewPages }
}
