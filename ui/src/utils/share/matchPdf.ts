import { jsPDF } from 'jspdf'
import { fitLogo, MAX_SHARE_SPONSORS } from './logoLayout'
import type { Rect } from './logoLayout'
import { PDF_PAGE_HEIGHT, PDF_PAGE_WIDTH } from './resultPdf'
import type { PdfOp, ResultPdfLogos, ResultPdfOutput } from './resultPdf'
import { readableOn } from './resultImage'
import type { ResultImageColour } from './resultImage'
import type { PdfTemplate } from './shareChoices'
import type { MatchShareLineup, MatchShareModel } from './shareMatchData'

// docs/specs/131-match-sharing.md (Team sheet A4, PDF format): one A4 document for any match content, laid out into the same
// PdfOp lists the result and league PDFs use (so drawResultPdfPage previews it) and replayed into jsPDF. Names come from the
// MatchShareModel (already through shareName). Metadata carries team and league names only. A team sheet prints on one page.

type Rgb = [number, number, number]
type Align = 'left' | 'right' | 'center'
type Font = 'normal' | 'bold' | 'italic'

const WHITE: Rgb = [255, 255, 255]
const INK: Rgb = [20, 35, 28]
const MUTED: Rgb = [82, 101, 92]
const RULE: Rgb = [229, 235, 231]
const ON_CLUB_WHITE = 'rgb(255, 255, 255)'
const ON_CLUB_INK = 'rgb(20, 35, 28)'
const PLATFORM_CREDIT = 'Generated by Cricket Legend'
const MM_PER_PT = 25.4 / 72

const SCALE: Record<PdfTemplate, { title: number; body: number; small: number; row: number }> = {
  CLUB: { title: 17, body: 10, small: 7.5, row: 6.6 },
  CLASSIC: { title: 17, body: 10, small: 7.5, row: 6.6 },
  COMPACT: { title: 14, body: 8.5, small: 7, row: 5.4 },
}

export interface MatchPdfOptions {
  template: PdfTemplate
  colour: ResultImageColour
  include: { marks: boolean; venueAndDate: boolean; weather: boolean }
  logos: ResultPdfLogos
  clubWebsite: string | null
  footerLine: boolean
}

function toRgb(css: string, fallback: Rgb): Rgb {
  const hex = /^#?([0-9a-f]{3}|[0-9a-f]{6})$/i.exec(css.trim())
  if (hex) {
    const digits = hex[1].length === 3 ? hex[1].replace(/./g, '$&$&') : hex[1]
    return [parseInt(digits.slice(0, 2), 16), parseInt(digits.slice(2, 4), 16), parseInt(digits.slice(4, 6), 16)]
  }
  const rgb = /^rgba?\(\s*(\d+)[,\s]+(\d+)[,\s]+(\d+)/i.exec(css.trim())
  return rgb ? [Number(rgb[1]), Number(rgb[2]), Number(rgb[3])] : fallback
}

async function loadImageBase64(url: string): Promise<string | null> {
  try {
    const response = await fetch(url)
    if (!response.ok) return null
    const blob = await response.blob()
    return await new Promise<string>((resolve, reject) => {
      const reader = new FileReader()
      reader.onload = () => resolve(reader.result as string)
      reader.onerror = () => reject(reader.error)
      reader.readAsDataURL(blob)
    })
  } catch {
    return null
  }
}

const imageFormat = (data: string): string => (/^data:image\/jpe?g/i.test(data) ? 'JPEG' : 'PNG')
const roleText = (captain: boolean, keeper: boolean): string => [captain ? 'Captain' : '', keeper ? 'Wicketkeeper' : ''].filter(Boolean).join(', ')

export async function generateMatchPdf(model: MatchShareModel, options: MatchPdfOptions): Promise<ResultPdfOutput> {
  const type = SCALE[options.template]
  const clubRgb = toRgb(options.colour.main, INK)
  const onClub = toRgb(readableOn([options.colour.main], [options.colour.contrastText, ON_CLUB_WHITE, ON_CLUB_INK]), WHITE)
  const sponsorUrls = options.logos.sponsorUrls.slice(0, MAX_SHARE_SPONSORS)
  const wanted = [options.logos.clubUrl, options.logos.leagueUrl, ...sponsorUrls].filter((url): url is string => Boolean(url))
  const loaded = new Map<string, string | null>(await Promise.all([...new Set(wanted)].map(async (url) => [url, await loadImageBase64(url)] as const)))
  const imageOf = (url: string | null): string | null => (url ? (loaded.get(url) ?? null) : null)

  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' })
  doc.setProperties({
    title: model.title,
    subject: [model.leagueName, model.seasonLabel].filter(Boolean).join(', ') || 'Match',
    author: model.clubName || 'Cricket Legend',
    creator: 'Cricket Legend',
  })

  const pageW = PDF_PAGE_WIDTH
  const pageH = PDF_PAGE_HEIGHT
  const margin = 14
  const left = margin
  const right = pageW - margin
  const contentW = right - left
  const pages: PdfOp[][] = []
  let y = 0

  const push = (op: PdfOp) => pages[pages.length - 1].push(op)
  const fillRect = (x: number, top: number, width: number, height: number, colour: Rgb, radius = 0) => push({ kind: 'rect', x, y: top, width, height, radius, fill: colour })
  const text = (value: string, x: number, baseline: number, size: number, colour: Rgb, font: Font = 'normal', align: Align = 'left') => {
    if (value) push({ kind: 'text', text: value, x, y: baseline, align, font, size, colour })
  }
  const rule = (x1: number, y1: number, x2: number, colour: Rgb, lineWidth = 0.2) => push({ kind: 'line', x1, y1, x2, y2: y1, colour, lineWidth })
  const measure = (value: string, size: number, font: Font = 'normal'): number => {
    doc.setFont('helvetica', font)
    doc.setFontSize(size)
    return doc.getTextWidth(value)
  }
  const fit = (value: string, width: number, size: number, font: Font = 'normal'): string => {
    if (measure(value, size, font) <= width) return value
    let cut = value
    while (cut.length > 1 && measure(`${cut}...`, size, font) > width) cut = cut.slice(0, -1)
    return `${cut.trimEnd()}...`
  }
  const placeImage = (data: string, slot: Rect) => {
    let natural = { width: 0, height: 0 }
    try {
      const properties = doc.getImageProperties(data)
      natural = { width: properties.width, height: properties.height }
    } catch {
      // Unknown size: the logo fills its slot.
    }
    const box = fitLogo(slot, natural.width, natural.height)
    push({ kind: 'image', data, x: box.x, y: box.y, width: box.width, height: box.height })
  }

  const header = () => {
    pages.push([])
    const band = 30
    fillRect(0, 0, pageW, band, clubRgb)
    const logoSize = 18
    let textLeft = left
    const clubImage = imageOf(options.logos.clubUrl)
    if (clubImage) {
      fillRect(left - 0.8, 6.2, logoSize + 1.6, logoSize + 1.6, WHITE, 2)
      placeImage(clubImage, { x: left, y: 7, width: logoSize, height: logoSize })
      textLeft = left + logoSize + 5
    }
    let textRight = right
    const leagueImage = imageOf(options.logos.leagueUrl)
    if (leagueImage) {
      fillRect(right - logoSize - 0.8, 6.2, logoSize + 1.6, logoSize + 1.6, WHITE, 2)
      placeImage(leagueImage, { x: right - logoSize, y: 7, width: logoSize, height: logoSize })
      textRight = right - logoSize - 5
    }
    const width = textRight - textLeft
    text(fit(model.title, width, type.title, 'bold'), textLeft, 14, type.title, onClub, 'bold')
    const sub = [model.leagueName, model.seasonLabel].filter(Boolean).join(' · ')
    text(fit(sub, width, type.body), textLeft, 21, type.body, onClub)
    y = band + 8
  }

  const detailLines = () => {
    const lines: string[] = []
    if (options.include.venueAndDate) lines.push([model.whenLabel, model.venue].filter(Boolean).join(' · '))
    if (options.include.weather && model.weather) lines.push(`Forecast: ${model.weather.text}`)
    lines.forEach((line, index) => {
      text(fit(line, contentW, type.body + 1, index === 0 ? 'bold' : 'normal'), left, y, type.body + 1, index === 0 ? INK : [20, 99, 63], index === 0 ? 'bold' : 'normal')
      y += type.body * MM_PER_PT + 2.6
    })
    y += 2
  }

  const table = (lineup: MatchShareLineup, x: number, width: number) => {
    text(fit(lineup.teamName, width, type.body + 3, 'bold'), x, y, type.body + 3, INK, 'bold')
    let rowY = y + 3
    rule(x, rowY, x + width, INK, 0.3)
    rowY += type.row - 1
    text('#', x, rowY, type.small + 1, MUTED, 'bold')
    text('Player', x + 9, rowY, type.small + 1, MUTED, 'bold')
    text('Role', x + width, rowY, type.small + 1, MUTED, 'bold', 'right')
    rowY += 1.6
    rule(x, rowY, x + width, RULE)
    let position = 0
    lineup.players.forEach((player) => {
      rowY += type.row
      const roles = options.include.marks ? roleText(player.captain, player.keeper) : ''
      text(player.order != null ? String((position += 1)) : '', x, rowY, type.body, MUTED)
      text(fit(player.name, width - 9 - (roles ? 34 : 0), type.body), x + 9, rowY, type.body, INK)
      text(roles, x + width, rowY, type.small + 1, MUTED, 'normal', 'right')
      rule(x, rowY + 1.6, x + width, RULE)
    })
    if (lineup.twelfthMan) {
      rowY += type.row
      text(fit(`12th man: ${lineup.twelfthMan}`, width, type.body), x, rowY, type.body, MUTED, 'italic')
    }
    return rowY
  }

  const blankLines = () => {
    for (const label of ['Scorers', 'Toss won by', 'Signed (captain)']) {
      y += 11
      rule(left, y, right, INK, 0.25)
      text(label, left, y + 3.6, type.small, MUTED)
    }
  }

  const bigText = (value: string, size: number, colour: Rgb, font: Font = 'bold') => {
    text(fit(value, contentW, size, font), pageW / 2, y, size, colour, font, 'center')
    y += size * MM_PER_PT + 4
  }

  const sheet = model.lineups
  if ((model.content === 'TEAM_SHEET' || model.content === 'TEAM_SELECTION') && sheet.length > 0) {
    const sideBySide = sheet.length > 1 && model.layout === 'SIDE_BY_SIDE'
    if (sideBySide) {
      header()
      detailLines()
      const gap = 8
      const half = (contentW - gap) / 2
      const ends = sheet.map((lineup, index) => table(lineup, left + index * (half + gap), half))
      y = Math.max(...ends) + 4
      if (model.content === 'TEAM_SHEET') blankLines()
    } else {
      sheet.forEach((lineup) => {
        header()
        detailLines()
        y = table(lineup, left, contentW) + 4
        if (model.content === 'TEAM_SHEET') blankLines()
      })
    }
  } else {
    header()
    y += 4
    if (model.content === 'COUNTDOWN') {
      y += 12
      bigText((model.countdown ?? '').toUpperCase(), 40, clubRgb)
    } else {
      y += 8
    }
    if (model.content !== 'FUN_FACTS') bigText(`${model.homeName} v ${model.awayName}`, 20, INK)
    y += 2
    if (model.content === 'FUN_FACTS') {
      detailLines()
      if (model.facts.length === 0) text('No facts to share yet.', left, y, type.body, MUTED, 'italic')
      model.facts.slice(0, 5).forEach((fact) => {
        fillRect(left, y - 5, 1.2, 10, clubRgb)
        text(fit(fact.text, contentW - 6, type.body + 2, 'bold'), left + 4, y, type.body + 2, INK, 'bold')
        text(fit(fact.basis, contentW - 6, type.small), left + 4, y + 4.2, type.small, MUTED)
        y += 15
      })
    } else {
      const lines: string[] = []
      if (options.include.venueAndDate) lines.push(model.whenLabel, model.venue ?? '')
      if (options.include.weather && model.weather) lines.push(`Forecast: ${model.weather.text}`)
      lines.filter(Boolean).forEach((line) => {
        text(fit(line, contentW, type.body + 3), pageW / 2, y, type.body + 3, MUTED, 'normal', 'center')
        y += 8
      })
    }
  }

  // Footer and sponsors on every page.
  pages.forEach((_, index) => {
    const into = (op: PdfOp) => pages[index].push(op)
    const sponsors = sponsorUrls.map(imageOf).filter((data): data is string => data !== null)
    if (sponsors.length > 0) {
      const box = 12
      const total = sponsors.length * box + (sponsors.length - 1) * 4
      sponsors.forEach((data, position) => {
        const slot = { x: (pageW - total) / 2 + position * (box + 4), y: pageH - margin - 14 - box, width: box, height: box }
        const natural = (() => {
          try {
            const properties = doc.getImageProperties(data)
            return { width: properties.width, height: properties.height }
          } catch {
            return { width: 0, height: 0 }
          }
        })()
        const fitted = fitLogo(slot, natural.width, natural.height)
        into({ kind: 'image', data, x: fitted.x, y: fitted.y, width: fitted.width, height: fitted.height })
      })
    }
    if (options.footerLine) {
      const site = options.clubWebsite?.trim().replace(/^https?:\/\//i, '').replace(/\/$/, '')
      into({ kind: 'line', x1: left, y1: pageH - margin - 6, x2: right, y2: pageH - margin - 6, colour: RULE, lineWidth: 0.2 })
      if (site) into({ kind: 'text', text: site, x: left, y: pageH - margin - 1.5, align: 'left', font: 'normal', size: type.small, colour: MUTED })
      into({ kind: 'text', text: PLATFORM_CREDIT, x: right, y: pageH - margin - 1.5, align: 'right', font: 'normal', size: type.small, colour: MUTED })
    }
  })

  const previewPages: PdfOp[][] = []
  pages.forEach((ops, index) => {
    if (index > 0) doc.addPage()
    const kept: PdfOp[] = []
    for (const op of ops) {
      if (op.kind === 'rect') {
        doc.setFillColor(...op.fill)
        if (op.radius > 0) doc.roundedRect(op.x, op.y, op.width, op.height, op.radius, op.radius, 'F')
        else doc.rect(op.x, op.y, op.width, op.height, 'F')
      } else if (op.kind === 'line') {
        doc.setDrawColor(...op.colour)
        doc.setLineWidth(op.lineWidth)
        doc.line(op.x1, op.y1, op.x2, op.y2)
      } else if (op.kind === 'text') {
        doc.setTextColor(...op.colour)
        doc.setFont('helvetica', op.font)
        doc.setFontSize(op.size)
        doc.text(op.text, op.x, op.y, { align: op.align })
      } else {
        try {
          doc.addImage(op.data, imageFormat(op.data), op.x, op.y, op.width, op.height)
        } catch {
          continue
        }
      }
      kept.push(op)
    }
    previewPages.push(kept)
  })
  const blob = doc.output('blob')
  return { blob, url: URL.createObjectURL(blob), pageCount: pages.length, pages: previewPages }
}
