import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'

const textSpy = vi.fn()
const addPageSpy = vi.fn()

vi.mock('jspdf', () => {
  class MockJsPDF {
    setFillColor = vi.fn()
    setDrawColor = vi.fn()
    setLineWidth = vi.fn()
    setTextColor = vi.fn()
    setFont = vi.fn()
    setFontSize = vi.fn()
    setProperties = vi.fn()
    rect = vi.fn()
    roundedRect = vi.fn()
    line = vi.fn()
    text = textSpy
    addImage = vi.fn()
    addPage = addPageSpy
    getTextWidth = (value: string) => value.length * 1.6
    output = vi.fn(() => new Blob(['fake-pdf']))
  }
  return { jsPDF: MockJsPDF }
})

import type { Match } from '../../api/matchApi'
import { generateLeagueSharePoster } from '../leagueSchedulePoster'
import { generateLeaguePdf } from './leaguePdf'
import { buildLeagueShareModel } from './shareLeagueData'
import { leagueInput } from './sharePrivacyFixture'

const colour = { main: '#2f6e4f', dark: '#234f39', contrastText: '#ffffff' }
const pdfOptions = { colour, logos: { clubUrl: null, leagueUrl: null, teams: false, sponsorUrls: [] }, clubWebsite: 'https://riverside-cc.example/', footerLine: true, resultLine: true }
const model = (contents: string[], overrides = {}) => buildLeagueShareModel(leagueInput(false, { contents, ...overrides }))
const drawn = () => textSpy.mock.calls.map((call) => String(call[0]))

describe('generateLeaguePdf', () => {
  beforeEach(() => {
    vi.clearAllMocks()
    vi.stubGlobal('URL', Object.assign(URL, { createObjectURL: vi.fn(() => 'blob:pdf'), revokeObjectURL: vi.fn() }))
  })
  afterEach(() => vi.unstubAllGlobals())

  it('draws a section per ticked content in the standard order, and none for an unticked one', async () => {
    const out = await generateLeaguePdf(model(['RESULTS', 'TEAMS', 'DETAILS']), pdfOptions)
    const texts = drawn()
    const at = (label: string) => texts.findIndex((t) => t.toLowerCase() === label.toLowerCase())
    expect(at('League details')).toBeGreaterThanOrEqual(0)
    expect(at('League details')).toBeLessThan(at('Teams'))
    expect(at('Teams')).toBeLessThan(at('Results'))
    expect(at('Schedule')).toBe(-1)
    expect(out.url).toBe('blob:pdf')
    expect(out.pageCount).toBe(1)
  })

  it('shows a plain note for a ticked content that has nothing yet', async () => {
    await generateLeaguePdf(model(['KEY_DATES'], { seasonDates: null, matches: [] }), pdfOptions)
    expect(drawn()).toContain('No dates set for this season yet.')
  })

  it('starts a new page when the schedule is long', async () => {
    const matches = Array.from({ length: 120 }, (_, index) => ({ ...leagueInput(false).matches[0], id: `m${index}`, active: true, matchDate: `2026-11-01T${String(index % 24).padStart(2, '0')}:00:00` })) as Match[]
    const out = await generateLeaguePdf(model(['SCHEDULE'], { matches }), pdfOptions)
    expect(out.pageCount).toBeGreaterThan(1)
    expect(addPageSpy).toHaveBeenCalledTimes(out.pageCount - 1)
    expect(drawn().some((t) => t.startsWith(`Page 2 of ${out.pageCount}`))).toBe(true)
  })

  it('carries the platform credit and website in the footer, and leaves both out with the footer line off', async () => {
    await generateLeaguePdf(model(['TEAMS']), pdfOptions)
    const footer = drawn().find((t) => t.startsWith('Page 1 of 1'))
    expect(footer).toBe('Page 1 of 1 · riverside-cc.example · Generated by Cricket Legend')
    vi.clearAllMocks()
    await generateLeaguePdf(model(['TEAMS']), { ...pdfOptions, footerLine: false })
    expect(drawn().find((t) => t.startsWith('Page 1 of 1'))).toBe('Page 1 of 1')
    expect(drawn().join('\n')).not.toContain('Generated by Cricket Legend')
  })
})

describe('generateLeagueSharePoster', () => {
  const texts: string[] = []
  beforeEach(() => {
    texts.length = 0
    const ctx = {
      fillRect: vi.fn(),
      fillText: (text: string) => texts.push(String(text)),
      drawImage: vi.fn(),
      createLinearGradient: () => ({ addColorStop: vi.fn() }),
      measureText: (text: string) => ({ width: text.length * 6 }),
      beginPath: vi.fn(),
      moveTo: vi.fn(),
      arcTo: vi.fn(),
      closePath: vi.fn(),
      fill: vi.fn(),
      fillStyle: '',
      font: '',
      textAlign: 'left',
      textBaseline: 'alphabetic',
    }
    vi.spyOn(HTMLCanvasElement.prototype, 'getContext').mockReturnValue(ctx as unknown as CanvasRenderingContext2D)
    vi.spyOn(HTMLCanvasElement.prototype, 'toBlob').mockImplementation(function (callback) {
      callback!(new Blob(['png']))
    })
    vi.stubGlobal('URL', Object.assign(URL, { createObjectURL: vi.fn(() => 'blob:poster'), revokeObjectURL: vi.fn() }))
    vi.stubGlobal('fetch', vi.fn().mockRejectedValue(new Error('offline')))
  })
  afterEach(() => {
    vi.unstubAllGlobals()
    vi.restoreAllMocks()
  })

  it('draws the teams and the upcoming fixtures and returns a blob url', async () => {
    const url = await generateLeagueSharePoster(model(['TEAMS', 'SCHEDULE']), colour.main, { teamLogos: true, now: new Date('2026-10-18T00:00:00') })
    expect(url).toBe('blob:poster')
    const joined = texts.join('\n')
    expect(joined).toContain('Pretoria CC')
    expect(joined).toContain('Riverside 1')
  })

  it('draws the footer mark by default and omits it with footer: false', async () => {
    await generateLeagueSharePoster(model(['TEAMS']), colour.main, { teamLogos: false })
    expect(texts).toContain('Generated by Cricket Legend')
    texts.length = 0
    await generateLeagueSharePoster(model(['TEAMS']), colour.main, { teamLogos: false, footer: false })
    expect(texts).not.toContain('Generated by Cricket Legend')
  })

  it('counts rows that do not fit instead of drawing them', async () => {
    const matches = Array.from({ length: 40 }, (_, index) => ({ ...leagueInput(false).matches[0], id: `m${index}`, active: true, matchDate: `2026-11-${String((index % 28) + 1).padStart(2, '0')}T10:00:00` })) as Match[]
    await generateLeagueSharePoster(model(['SCHEDULE'], { matches }), colour.main, { teamLogos: false, now: new Date('2026-10-18T00:00:00') })
    expect(texts.some((t) => /^and \d+ more/.test(t))).toBe(true)
  })
})
