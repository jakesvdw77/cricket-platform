import { Typography } from '@mui/material'
import { CompactSwitch } from '../CompactSwitch'
import { MAX_SHARE_SPONSORS } from '../../utils/share/logoLayout'
import { ShareControlGroup } from './ShareControlGroup'
import { ShareSponsorChooser } from './ShareSponsorChooser'
import type { ShareCoreScreenProps } from './shareScreenTypes'

type Props = Pick<
  ShareCoreScreenProps,
  'choices' | 'updateChoices' | 'sponsors' | 'selectedSponsorIds' | 'clubLogoUrl' | 'leagueLogoUrl' | 'clubWebsite'
>

// docs/specs/114-share-result.md (Logos and footer): the Logos group and the Footer line switch shared by Image and TV.
// The League logo switch is hidden when the league has no logo; the Club logo switch says so when there is none to show.
export function ShareLogoControls({
  choices,
  updateChoices,
  sponsors,
  selectedSponsorIds,
  clubLogoUrl,
  leagueLogoUrl,
  clubWebsite,
}: Props) {
  const setLogo = (patch: Partial<typeof choices.logos>) => updateChoices({ logos: patch })
  return (
    <>
      <ShareControlGroup label="Logos">
        <CompactSwitch
          label="Club logo"
          checked={Boolean(clubLogoUrl) && choices.logos.club}
          disabled={!clubLogoUrl}
          describedBy={clubLogoUrl ? undefined : 'share-club-logo-reason'}
          onChange={(next) => setLogo({ club: next })}
        />
        {!clubLogoUrl && (
          <Typography id="share-club-logo-reason" variant="caption" color="text.secondary">
            No club logo available
          </Typography>
        )}
        <CompactSwitch label="Team logos" checked={choices.logos.team} onChange={(next) => setLogo({ team: next })} />
        {leagueLogoUrl && (
          <CompactSwitch label="League logo" checked={choices.logos.league} onChange={(next) => setLogo({ league: next })} />
        )}
        <Typography variant="caption" color="text.secondary" component="p" sx={{ mt: 0.5, fontWeight: 700 }}>
          Sponsor logos
        </Typography>
        <ShareSponsorChooser
          sponsors={sponsors}
          selectedIds={selectedSponsorIds}
          max={MAX_SHARE_SPONSORS}
          onChange={(ids) => updateChoices({ sponsorIds: ids })}
        />
      </ShareControlGroup>
      <ShareControlGroup label="Footer">
        <CompactSwitch
          label="Footer line"
          checked={choices.footerLine}
          describedBy="share-footer-line-help"
          onChange={(next) => updateChoices({ footerLine: next })}
        />
        <Typography id="share-footer-line-help" variant="caption" color="text.secondary">
          {clubWebsite
            ? 'The web address and "Generated by Cricket Legend".'
            : 'The platform credit. The web address shows once your club profile has a website.'}
        </Typography>
      </ShareControlGroup>
    </>
  )
}
